// The Turkish count inventory of I18N-12c (2026-10-28), data for `turkishCounts.contract.test.ts`.
//
// A Turkish value prints a plain placeholder exactly as the caller passes it: a raw 1204 shows as
// `1204` while the rest of the page says `1.204`. So every placeholder a caller fills with a raw
// number that can reach 1,000 is written `{name, number}` in the Turkish value (CONVERTED). Every
// other count-like placeholder that is still plain is listed in PLAIN with the reason it is safe:
//   string  - the caller passes a string already formatted for the locale (`formatCount(n, locale)`);
//   bounded - the caller passes a raw number, but a small one (a page size, a constant cap, seconds
//             or minutes of one clock part, a class count, a selection of at most five values);
//   unused  - no caller reads the key yet; whoever adds one decides (and moves it to CONVERTED).
// A new Turkish key with a plain count-like placeholder fails the test until it is classified here.

