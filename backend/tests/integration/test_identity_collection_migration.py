"""Migration 0069 widens the Ariel caller check and seeds the identity cadence."""

from __future__ import annotations

import os
import uuid
from datetime import UTC, datetime

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

from tests.integration.schema_reset import reset_public_schema

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif("TEST_DATABASE_URL" not in os.environ, reason="set TEST_DATABASE_URL"),
]

NOW = datetime(2026, 11, 13, 12, 0, tzinfo=UTC)
INSERT_RUN = text(
    "INSERT INTO ariel_search_run (id, caller, submitted_at, finished_at, polls, outcome) "
    "VALUES (:id, :caller, :at, :at, 1, 'COMPLETED')"
)


def _sync_url() -> str:
    return os.environ["TEST_DATABASE_URL"].replace("+asyncpg", "+psycopg")


def _config():  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", _sync_url())
    return config


def test_0069_round_trip_seeds_fifteen_minutes_and_checks_clean() -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    sync_url = _sync_url()
    reset_public_schema(sync_url)
    config = _config()
    engine = create_engine(sync_url, future=True)
    try:
        command.upgrade(config, "head")
        identity_id, kept_id = uuid.uuid4(), uuid.uuid4()
        with engine.begin() as connection:
            connection.execute(
                INSERT_RUN,
                {"id": identity_id, "caller": "IDENTITY_COLLECTION", "at": NOW},
            )
            connection.execute(INSERT_RUN, {"id": kept_id, "caller": "RULE_MATCH", "at": NOW})
            cadence = connection.execute(
                text(
                    "SELECT cadence_seconds FROM search_cadence "
                    "WHERE family = 'IDENTITY_COLLECTION'"
                )
            ).scalar()
            assert cadence == 900
            audits = connection.execute(text("SELECT count(*) FROM audit_log")).scalar()
            assert connection.execute(
                text("SELECT count(*) FROM audit_log WHERE object_id = 'IDENTITY_COLLECTION'")
            ).scalar() == 0

        command.downgrade(config, "0068")
        with engine.begin() as connection:
            ids = set(connection.execute(text("SELECT id FROM ariel_search_run")).scalars())
            assert ids == {kept_id}
            assert connection.execute(
                text(
                    "SELECT count(*) FROM search_cadence WHERE family = 'IDENTITY_COLLECTION'"
                )
            ).scalar() == 0
        with pytest.raises(IntegrityError), engine.begin() as connection:
            connection.execute(
                INSERT_RUN, {"id": uuid.uuid4(), "caller": "IDENTITY_COLLECTION", "at": NOW}
            )

        command.upgrade(config, "head")
        with engine.begin() as connection:
            assert connection.execute(
                text(
                    "SELECT cadence_seconds FROM search_cadence "
                    "WHERE family = 'IDENTITY_COLLECTION'"
                )
            ).scalar() == 900
            assert connection.execute(text("SELECT count(*) FROM audit_log")).scalar() == audits
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
