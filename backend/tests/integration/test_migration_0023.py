"""Migration 0023: saved dashboards, round trip, constraints and no drift."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import DataError, IntegrityError

from tests.integration.schema_reset import reset_public_schema

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")
DASHBOARD_COLUMNS = {
    "id": ("uuid", "NO"),
    "owner_subject": ("character varying", "NO"),
    "name": ("character varying", "NO"),
    "description": ("text", "YES"),
    "visibility": ("character varying", "NO"),
    "template_key": ("character varying", "YES"),
    "template_version": ("integer", "YES"),
    "schema_version": ("integer", "NO"),
    "layout": ("jsonb", "NO"),
    "revision": ("integer", "NO"),
    "created_at": ("timestamp with time zone", "NO"),
    "updated_at": ("timestamp with time zone", "NO"),
    "updated_by": ("character varying", "YES"),
}
PREF_COLUMNS = {
    "owner_subject": ("character varying", "NO"),
    "default_dashboard_id": ("uuid", "YES"),
    "updated_at": ("timestamp with time zone", "NO"),
}


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def _exists(connection, table: str) -> bool:  # type: ignore[no-untyped-def]
    return bool(
        connection.execute(
            text("SELECT to_regclass(:table)").bindparams(table=f"public.{table}")
        ).scalar()
    )


def _columns(connection, table: str) -> dict[str, tuple[str, str]]:  # type: ignore[no-untyped-def]
    return {
        row.column_name: (row.data_type, row.is_nullable)
        for row in connection.execute(
            text(
                "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
                "WHERE table_name = :t"
            ),
            {"t": table},
        )
    }


def _insert(connection, owner="alice", name="Main", **over) -> str:  # type: ignore[no-untyped-def]
    values = {
        "o": owner,
        "n": name,
        "v": "PRIVATE",
        "s": 1,
        "r": 1,
        **over,
    }
    return str(
        connection.execute(
            text(
                "INSERT INTO dashboard (id, owner_subject, name, visibility, schema_version, "
                "layout, revision) VALUES (gen_random_uuid(), :o, :n, :v, :s, "
                "CAST('{\"v\": 1, \"range\": \"24h\", \"widgets\": []}' AS jsonb), :r) RETURNING id"
            ),
            values,
        ).scalar_one()
    )


def _rejected(engine, **over) -> bool:  # type: ignore[no-untyped-def]
    try:
        with engine.begin() as connection:
            _insert(connection, **over)
    except (IntegrityError, DataError):
        return True
    return False


def test_0023_round_trip_constraints_and_no_drift(clean_db: str) -> None:
    from alembic.script import ScriptDirectory
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    assert ScriptDirectory.from_config(config).get_revision("0023").down_revision == "0022"
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "0023")
        with engine.begin() as connection:
            assert _columns(connection, "dashboard") == DASHBOARD_COLUMNS
            assert _columns(connection, "user_dashboard_pref") == PREF_COLUMNS
            # Seeds nothing: templates live in the frontend.
            assert connection.execute(text("SELECT count(*) FROM dashboard")).scalar_one() == 0
            indexes = {
                row.indexname: row.indexdef
                for row in connection.execute(
                    text("SELECT indexname, indexdef FROM pg_indexes WHERE tablename = 'dashboard'")
                )
            }
            assert "(owner_subject, updated_at DESC)" in indexes["ix_dashboard_owner"]

        # The unique constraint: a name is unique per owner, not globally.
        with engine.begin() as connection:
            _insert(connection, owner="alice", name="Main")
            _insert(connection, owner="bob", name="Main")
        assert _rejected(engine, owner="alice", name="Main")
        # The CHECKs.
        assert _rejected(engine, name="bad-visibility", v="TEAM")
        assert _rejected(engine, name="bad-schema", s=0)
        assert _rejected(engine, name="bad-revision", r=0)
        # The name column is 80 characters.
        assert _rejected(engine, name="x" * 81)

        # ON DELETE SET NULL clears a default pointing at a deleted dashboard.
        with engine.begin() as connection:
            target = _insert(connection, owner="alice", name="Default me")
            connection.execute(
                text("INSERT INTO user_dashboard_pref (owner_subject, default_dashboard_id) "
                     "VALUES ('alice', :d)"),
                {"d": target},
            )
            delete_rule = connection.execute(
                text(
                    "SELECT rc.delete_rule FROM information_schema.referential_constraints rc "
                    "JOIN information_schema.key_column_usage kcu "
                    "ON kcu.constraint_name = rc.constraint_name "
                    "WHERE kcu.table_name = 'user_dashboard_pref'"
                )
            ).scalar_one()
            assert delete_rule == "SET NULL"
            connection.execute(text("DELETE FROM dashboard WHERE id = :d"), {"d": target})
            row = connection.execute(
                text("SELECT default_dashboard_id FROM user_dashboard_pref "
                     "WHERE owner_subject = 'alice'")
            ).one()
            assert row.default_dashboard_id is None

        command.downgrade(config, "0022")
        with engine.connect() as connection:
            assert not _exists(connection, "dashboard")
            assert not _exists(connection, "user_dashboard_pref")
            assert _exists(connection, "geo_country_bucket")

        command.upgrade(config, "0023")
        with engine.connect() as connection:
            assert _exists(connection, "dashboard")
            assert _exists(connection, "user_dashboard_pref")
        # Drift is checked at head, so a later migration cannot hide a model gap.
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
