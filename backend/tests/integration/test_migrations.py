def test_0015_waf_validation_request_round_trip(clean_db: str) -> None:
    """Pending-validation columns add and remove cleanly without schema drift.

    The round trip is pinned to revision 0015 (up to 0015, down to 0014), so later
    migrations on top of it do not break it; the drift check still runs at head.
    """
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(cfg, "0014")
        with engine.connect() as conn:
            before = {
                row.column_name
                for row in conn.execute(
                    text(
                        "SELECT column_name FROM information_schema.columns "
                        "WHERE table_name = 'waf_source_profile'"
                    )
                )
            }
        assert "validation_requested_at" not in before
        assert "validation_requested_by" not in before

        command.upgrade(cfg, "0015")
        with engine.connect() as conn:
            added = {
                row.column_name: row.is_nullable
                for row in conn.execute(
                    text(
                        "SELECT column_name, is_nullable FROM information_schema.columns "
                        "WHERE table_name = 'waf_source_profile' AND "
                        "column_name LIKE 'validation_requested_%'"
                    )
                )
            }
        assert added == {
            "validation_requested_at": "YES",
            "validation_requested_by": "YES",
        }

        command.downgrade(cfg, "0014")
        with engine.connect() as conn:
            after_downgrade = conn.execute(
                text(
                    "SELECT count(*) FROM information_schema.columns "
                    "WHERE table_name = 'waf_source_profile' AND "
                    "column_name LIKE 'validation_requested_%'"
                )
            ).scalar()
        assert after_downgrade == 0

        command.upgrade(cfg, "head")
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()

    # Re-upgrade must succeed on the now-empty database.
    command.upgrade(cfg, "head")
    engine = create_engine(clean_db, future=True)
    try:
        assert _table_exists(engine, "log_source")
    finally:
        engine.dispose()


