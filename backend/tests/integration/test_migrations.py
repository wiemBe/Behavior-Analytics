def test_0033_ui_language_round_trip(clean_db: str) -> None:
    """0033 adds the account's interface language additively and reversibly.

    A user row written at 0032 reads 'en' at head, the backfill default is
    transient (a fresh install has none), the check constraint refuses any
    other value, and the downgrade drops the column without touching the row.
    """
    from alembic.util.exc import AutogenerateDiffsDetected
    from sqlalchemy.exc import IntegrityError

    from alembic import command

    cfg = _alembic_config(clean_db)
    command.upgrade(cfg, "0032")
    user_id = "44444444-4444-4444-4444-444444444444"
    engine = create_engine(clean_db, future=True)
    try:
        with engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO app_user (id, email, is_active, auth_source, "
                    " must_change_password, failed_login_count) "
                    "VALUES (CAST(:u AS uuid), 'i18n@example.internal', true, 'LOCAL', "
                    "        false, 0)"
                ).bindparams(u=user_id)
            )

        command.upgrade(cfg, "0033")

        with engine.connect() as conn:
            language = conn.execute(
                text("SELECT ui_language FROM app_user WHERE id = CAST(:u AS uuid)").bindparams(
                    u=user_id
                )
            ).scalar()
            assert language == "en"
            default = conn.execute(
                text(
                    "SELECT column_default FROM information_schema.columns "
                    "WHERE table_schema = 'public' AND table_name = 'app_user' "
                    "AND column_name = 'ui_language'"
                )
            ).scalar()
            assert default is None

        with pytest.raises(IntegrityError, match="ui_language_known"), engine.begin() as conn:
            conn.execute(text("UPDATE app_user SET ui_language = 'de'"))
        with engine.begin() as conn:
            conn.execute(text("UPDATE app_user SET ui_language = 'tr'"))

        command.downgrade(cfg, "0032")
        with engine.connect() as conn:
            columns = {
                row[0]
                for row in conn.execute(
                    text(
                        "SELECT column_name FROM information_schema.columns "
                        "WHERE table_schema = 'public' AND table_name = 'app_user'"
                    )
                )
            }
            assert "ui_language" not in columns
            assert conn.execute(text("SELECT count(*) FROM app_user")).scalar() == 1

        command.upgrade(cfg, "head")
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()


