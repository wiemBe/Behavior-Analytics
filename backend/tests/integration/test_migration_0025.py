"""Migration 0025: sessions and directory config, carrying the seed account.

The passwordless ``admin@example.internal`` row is disabled, not deleted, and
its username stays NULL. A NULL email written after the upgrade becomes
``{id}@unspecified.invalid`` on the way back to 0024, where email is NOT NULL.
``alembic check`` runs at head.
"""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text

from tests.integration.schema_reset import reset_public_schema

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")
SEED = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaa1"
KEPT = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaa2"


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def _exists(connection, table: str) -> bool:  # type: ignore[no-untyped-def]
    return bool(
        connection.execute(
            text("SELECT to_regclass(:table)").bindparams(table=f"public.{table}")
        ).scalar()
    )


def test_0025_disables_the_seed_admin_and_round_trips(clean_db: str) -> None:
    from alembic.runtime.migration import MigrationContext
    from alembic.script import ScriptDirectory
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    script = ScriptDirectory.from_config(config)
    heads = script.get_heads()
    assert len(heads) == 1
    assert "0025" in {item.revision for item in script.walk_revisions("base", heads[0])}
    revision = script.get_revision("0025")
    assert revision is not None
    assert revision.down_revision == "0024"

    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "0024")
        with engine.begin() as connection:
            connection.execute(
                text(
                    "INSERT INTO app_user (id, email, display_name, hashed_password, is_active) "
                    "VALUES (CAST(:id AS uuid), 'admin@example.internal', 'Admin', NULL, true)"
                ),
                {"id": SEED},
            )
            connection.execute(
                text(
                    "INSERT INTO app_user (id, email, display_name, hashed_password, is_active) "
                    "VALUES (CAST(:id AS uuid), 'kept@example.internal', 'Kept', NULL, true)"
                ),
                {"id": KEPT},
            )

        command.upgrade(config, "0025")
        with engine.begin() as connection:
            seed = connection.execute(
                text(
                    "SELECT username, auth_source, hashed_password, must_change_password, "
                    "is_active, disabled_at IS NOT NULL "
                    "FROM app_user WHERE id = CAST(:id AS uuid)"
                ),
                {"id": SEED},
            ).one()
            assert seed == (None, "LOCAL", None, True, False, True)
            kept = connection.execute(
                text(
                    "SELECT is_active, must_change_password, email FROM app_user "
                    "WHERE id = CAST(:id AS uuid)"
                ),
                {"id": KEPT},
            ).one()
            assert kept == (True, False, "kept@example.internal")
            assert _exists(connection, "auth_session")
            assert _exists(connection, "ldap_config")
            directory = connection.execute(
                text(
                    "SELECT id, enabled, version, bind_template, timeout_seconds "
                    "FROM ldap_config"
                )
            ).one()
            assert directory == (1, False, 1, "{username}", 5)
            default = connection.execute(
                text(
                    "SELECT column_default FROM information_schema.columns "
                    "WHERE table_schema = 'public' AND table_name = 'ldap_config' "
                    "AND column_name = 'id'"
                )
            ).scalar_one()
            assert default is None
            connection.execute(
                text("UPDATE app_user SET email = NULL WHERE id = CAST(:id AS uuid)"),
                {"id": KEPT},
            )

        command.downgrade(config, "0024")
        with engine.connect() as connection:
            assert not _exists(connection, "auth_session")
            assert not _exists(connection, "ldap_config")
            columns = {
                row.column_name: row.is_nullable
                for row in connection.execute(
                    text(
                        "SELECT column_name, is_nullable FROM information_schema.columns "
                        "WHERE table_schema = 'public' AND table_name = 'app_user'"
                    )
                )
            }
            assert "username" not in columns
            assert "auth_source" not in columns
            assert columns["email"] == "NO"
            seed_active = connection.execute(
                text(
                    "SELECT is_active, hashed_password FROM app_user "
                    "WHERE id = CAST(:id AS uuid)"
                ),
                {"id": SEED},
            ).one()
            assert seed_active == (True, None)
            kept_email = connection.execute(
                text("SELECT email FROM app_user WHERE id = CAST(:id AS uuid)"),
                {"id": KEPT},
            ).scalar_one()
            assert kept_email == f"{KEPT}@unspecified.invalid"
            context = MigrationContext.configure(connection)
            assert context.get_current_revision() == "0024"

        command.upgrade(config, "head")
        with engine.connect() as connection:
            seed = connection.execute(
                text(
                    "SELECT username, is_active, disabled_at IS NOT NULL, hashed_password "
                    "FROM app_user WHERE id = CAST(:id AS uuid)"
                ),
                {"id": SEED},
            ).one()
            assert seed == (None, False, True, None)
            kept_email = connection.execute(
                text("SELECT email FROM app_user WHERE id = CAST(:id AS uuid)"),
                {"id": KEPT},
            ).scalar_one()
            assert kept_email == f"{KEPT}@unspecified.invalid"
            assert connection.execute(text("SELECT count(*) FROM ldap_config")).scalar_one() == 1
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
