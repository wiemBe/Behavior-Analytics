"""Migration 0021: IPS detector persistence, round trip and no drift."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")
TABLES = {
    "ips_entity_baseline",
    "ips_source_baseline",
    "ips_detector_state",
    "ips_anomaly",
    "ips_anomaly_transition",
}


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    engine = create_engine(sync_url, future=True)
    with engine.begin() as connection:
        connection.execute(text("DROP SCHEMA public CASCADE"))
        connection.execute(text("CREATE SCHEMA public"))
    engine.dispose()
    return sync_url


def _exists(connection, table: str) -> bool:  # type: ignore[no-untyped-def]
    return bool(
        connection.execute(
            text("SELECT to_regclass(:table)").bindparams(table=f"public.{table}")
        ).scalar()
    )


def test_0021_round_trip_constraints_cascades_and_no_drift(clean_db: str) -> None:
    from alembic.script import ScriptDirectory
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    assert ScriptDirectory.from_config(config).get_revision("0021").down_revision == "0020"
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "0021")
        with engine.connect() as connection:
            assert all(_exists(connection, table) for table in TABLES)
            assert connection.execute(
                text(
                    "SELECT is_nullable FROM information_schema.columns "
                    "WHERE table_name = 'ips_anomaly' AND column_name = 'fingerprint'"
                )
            ).scalar_one() == "NO"

            checks = {
                row.relname: row.definition
                for row in connection.execute(
                    text(
                        "SELECT cls.relname, pg_get_constraintdef(con.oid) AS definition "
                        "FROM pg_constraint con "
                        "JOIN pg_class cls ON cls.oid = con.conrelid "
                        "WHERE cls.relname IN ('ips_detector_state', 'ips_anomaly') "
                        "AND con.contype = 'c'"
                    )
                )
            }
            for definition in checks.values():
                assert "IPS_ENTITY" in definition and "IPS_SOURCE" in definition
                assert "ips_entity_id IS NOT NULL" in definition
                assert "log_source_id IS NOT NULL" in definition

            cascades = connection.execute(
                text(
                    "SELECT count(*) FROM pg_constraint con "
                    "JOIN pg_class cls ON cls.oid = con.conrelid "
                    "WHERE cls.relname = ANY(:tables) AND con.contype = 'f' "
                    "AND con.confdeltype = 'c'"
                ).bindparams(tables=list(TABLES))
            ).scalar_one()
            assert cascades == 7

            partial_uniques = {
                row.indexname: row.indexdef
                for row in connection.execute(
                    text(
                        "SELECT indexname, indexdef FROM pg_indexes "
                        "WHERE tablename = 'ips_detector_state'"
                    )
                )
            }
            assert "WHERE ((subject_kind)::text = 'IPS_ENTITY'::text)" in partial_uniques[
                "uq_ips_detector_state_entity"
            ]
            assert "WHERE ((subject_kind)::text = 'IPS_SOURCE'::text)" in partial_uniques[
                "uq_ips_detector_state_source"
            ]

            hypertables = connection.execute(
                text(
                    "SELECT count(*) FROM timescaledb_information.hypertables "
                    "WHERE hypertable_name = ANY(:tables)"
                ).bindparams(tables=list(TABLES))
            ).scalar_one()
            assert hypertables == 0

        command.downgrade(config, "0020")
        with engine.connect() as connection:
            assert not any(_exists(connection, table) for table in TABLES)
            assert _exists(connection, "ips_source_profile")
            assert _exists(connection, "ips_entity_metric")
            assert _exists(connection, "catchall_sender")

        command.upgrade(config, "head")
        with engine.connect() as connection:
            assert all(_exists(connection, table) for table in TABLES)
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
