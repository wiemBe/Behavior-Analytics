REASON = "QRADAR_DISABLED"
T0 = datetime(2026, 11, 20, 10, 0, tzinfo=UTC)
NOW = datetime(2026, 11, 20, 12, 0, tzinfo=UTC)


def _at(minutes: float) -> datetime:
    return T0 + timedelta(minutes=minutes)


async def _sources(session: AsyncSession, count: int = 1) -> list[uuid.UUID]:
    instance = await make_instance(session)
    return [
        (await make_log_source(session, instance, qradar_id=1000 + n, name=f"s{n}")).id
        for n in range(count)
    ]


async def _spans(session: AsyncSession) -> list[tuple[uuid.UUID, datetime, datetime | None]]:
    rows = await session.execute(
        select(LogSourcePause.log_source_id, LogSourcePause.starts_at, LogSourcePause.ends_at)
        .order_by(LogSourcePause.starts_at)
    )
    return [tuple(row) for row in rows]  # type: ignore[misc]


def _statements(session: AsyncSession) -> list[str]:
    """Collect the SQL the session issues on `log_source_pause` from now on."""
    seen: list[str] = []

    def record(conn: Any, cursor: Any, statement: str, *args: Any) -> None:
        if "log_source_pause" in statement:
            seen.append(statement)

    bind = session.bind
    assert bind is not None
    event.listen(bind.sync_engine, "before_cursor_execute", record)  # type: ignore[union-attr]
    return seen


# --- open / close ------------------------------------------------------------------------


async def test_edge_open_close_idempotent(db_session: AsyncSession) -> None:
    (source,) = await _sources(db_session)
    kw = {"reason": REASON, "now": NOW}

    assert await open_pause(db_session, [source], starts_at=_at(0), **kw) == 1
    assert await open_pause(db_session, [source], starts_at=_at(5), **kw) == 0
    assert await _spans(db_session) == [(source, _at(0), None)]

    close = {"reason": REASON, "bucket_seconds": 300}
    assert await close_pause(db_session, [source], observed_at=_at(62), **close) == 1
    assert await close_pause(db_session, [source], observed_at=_at(90), **close) == 0
    assert await _spans(db_session) == [(source, _at(0), _at(65))]

    # Re-opening after the close is a second, separate span.
    assert await open_pause(db_session, [source], starts_at=_at(100), **kw) == 1
    assert await _spans(db_session) == [(source, _at(0), _at(65)), (source, _at(100), None)]


async def test_open_and_close_are_one_statement_for_a_batch(db_session: AsyncSession) -> None:
    sources = await _sources(db_session, 5)
    seen = _statements(db_session)

    assert await open_pause(db_session, sources + sources, reason=REASON, starts_at=_at(0),
                            now=NOW) == 5
    assert len(seen) == 1
    assert await close_pause(db_session, sources, reason=REASON, observed_at=_at(10),
                             bucket_seconds=300) == 5
    assert len(seen) == 2
    assert len(await _spans(db_session)) == 5


async def test_redisable_at_an_unchanged_watermark_still_opens_a_span(
    db_session: AsyncSession,
) -> None:
    """A PARTIAL pass keeps the complete watermark still, so a source disabled, re-enabled
    and disabled again gets the same `starts_at`. That must open a span (starting where
    the closed one ended), not collide with its primary key and leave the source unpaused."""
    fresh, again = await _sources(db_session, 2)
    kw = {"reason": REASON, "now": NOW}
    await open_pause(db_session, [again], starts_at=_at(0), **kw)
    await close_pause(db_session, [again], reason=REASON, observed_at=_at(62),
                      bucket_seconds=300)

    # One statement, two sources: the clamp is per source.
    assert await open_pause(db_session, [fresh, again], starts_at=_at(0), **kw) == 2
    assert sorted(await _spans(db_session), key=lambda r: (r[0] != again, r[1])) == sorted(
        [(again, _at(0), _at(65)), (again, _at(65), None), (fresh, _at(0), None)],
        key=lambda r: (r[0] != again, r[1]),
    )
    # The re-opened span is an ordinary open span: a repeat changes nothing.
    assert await open_pause(db_session, [fresh, again], starts_at=_at(0), **kw) == 0

    # A closed end later than `now` (rounded up into the next bucket) is capped at now.
    close_soon = datetime(2026, 11, 20, 12, 1, tzinfo=UTC)
    await close_pause(db_session, [again], reason=REASON, observed_at=close_soon,
                      bucket_seconds=300)  # ends 12:05, after NOW (12:00)
    await open_pause(db_session, [again], reason=REASON, starts_at=_at(0), now=NOW)
    assert (again, NOW, None) in await _spans(db_session)


async def test_open_bounds_starts_at_to_now(db_session: AsyncSession) -> None:
    (source,) = await _sources(db_session)
    await open_pause(db_session, [source], reason=REASON, starts_at=NOW + timedelta(hours=3),
                     now=NOW)
    assert await _spans(db_session) == [(source, NOW, None)]


@pytest.mark.parametrize(
    ("observed_minutes", "ends_minutes"),
    [
        (62, 65),  # inside a bucket rounds up to the next boundary
        (65, 65),  # an exact boundary stays itself
        (65.0 + 1 / 60_000_000, 70),  # one microsecond past a boundary rounds up
        (64.999, 65),
    ],
)
async def test_close_rounds_up_to_bucket_boundary(
    db_session: AsyncSession, observed_minutes: float, ends_minutes: float
) -> None:
    (source,) = await _sources(db_session)
    await open_pause(db_session, [source], reason=REASON, starts_at=_at(0), now=NOW)
    await close_pause(db_session, [source], reason=REASON, observed_at=_at(observed_minutes),
                      bucket_seconds=300)
    assert await _spans(db_session) == [(source, _at(0), _at(ends_minutes))]


async def test_close_never_ends_before_one_second_after_start(db_session: AsyncSession) -> None:
    a, b = await _sources(db_session, 2)
    # Opened at an exact boundary and re-enabled at that same boundary, and one
    # re-enabled before it opened: ends_at must still be after starts_at.
    await open_pause(db_session, [a], reason=REASON, starts_at=_at(60), now=NOW)
    await open_pause(db_session, [b], reason=REASON, starts_at=_at(60), now=NOW)
    await close_pause(db_session, [a], reason=REASON, observed_at=_at(60), bucket_seconds=300)
    await close_pause(db_session, [b], reason=REASON, observed_at=_at(10), bucket_seconds=300)
    rows = {source: end for source, _, end in await _spans(db_session)}
    assert rows == {a: _at(60) + timedelta(seconds=1), b: _at(60) + timedelta(seconds=1)}


async def test_close_only_touches_the_open_span_of_that_reason(db_session: AsyncSession) -> None:
    one, two = await _sources(db_session, 2)
    await open_pause(db_session, [one, two], reason=REASON, starts_at=_at(0), now=NOW)
    await close_pause(db_session, [one], reason=REASON, observed_at=_at(10), bucket_seconds=300)
    await close_pause(db_session, [one, two], reason="OTHER", observed_at=_at(20),
                      bucket_seconds=300)
    assert {s: e for s, _, e in await _spans(db_session)} == {one: _at(10), two: None}


def test_previous_complete_or_first_seen_boundary() -> None:
    seen = datetime(2026, 11, 20, 9, 0, tzinfo=UTC)
    watermark = datetime(2026, 11, 20, 9, 30, tzinfo=UTC)
    # The previous complete watermark, when the source was already known.
    assert disable_edge_start(watermark, seen, NOW) == watermark
    # No complete watermark yet: first_seen_at.
    assert disable_edge_start(None, seen, NOW) == seen
    # Discovered after the watermark: first_seen_at, not the earlier watermark.
    after = datetime(2026, 11, 20, 9, 45, tzinfo=UTC)
    assert disable_edge_start(watermark, after, NOW) == after
    # A watermark or first_seen_at in the future is capped at now.
    future = NOW + timedelta(hours=1)
    assert disable_edge_start(future, seen, NOW) == NOW
    assert disable_edge_start(None, future, NOW) == NOW
    with pytest.raises(ValueError):
        disable_edge_start(None, datetime(2026, 11, 20, 9, 0), NOW)


