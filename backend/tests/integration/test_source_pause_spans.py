async def test_partial_boundary_bucket_overlap(db_session: AsyncSession) -> None:
    closed, only_open = await _sources(db_session, 2)
    await open_pause(db_session, [closed], reason=REASON, starts_at=_at(10), now=NOW)
    await close_pause(db_session, [closed], reason=REASON, observed_at=_at(20),
                      bucket_seconds=300)
    await open_pause(db_session, [only_open], reason=REASON, starts_at=_at(10), now=NOW)

    cases = [  # (source, bucket_start, bucket_end, overlaps)
        (closed, _at(5), _at(10), False),  # ends exactly at starts_at
        (closed, _at(5), _at(10) + timedelta(microseconds=1), True),
        (closed, _at(10), _at(15), True),
        (closed, _at(12), _at(14), True),  # wholly inside
        (closed, _at(15), _at(20), True),
        (closed, _at(20), _at(25), False),  # starts exactly at ends_at
        (closed, _at(20) - timedelta(microseconds=1), _at(25), True),
        (closed, _at(0), _at(60), True),  # swallows the span
        (only_open, _at(5), _at(10), False),
        (only_open, _at(9), _at(11), True),
        (only_open, _at(20), _at(25), True),  # an open span overlaps everything after
        (only_open, _at(5000), _at(5005), True),
        (uuid.uuid4(), _at(12), _at(14), False),  # another source
    ]
    buckets = values(
        column("source_id", PgUUID(as_uuid=True)),
        column("bucket_start", DateTime(timezone=True)),
        column("bucket_end", DateTime(timezone=True)),
        name="buckets",
    ).data([(s, a, b) for s, a, b, _ in cases])
    seen = _statements(db_session)
    rows = await db_session.execute(
        select(buckets.c.source_id, buckets.c.bucket_start, buckets.c.bucket_end)
        .where(bucket_overlaps_pause(buckets.c.source_id, buckets.c.bucket_start,
                                     buckets.c.bucket_end))
    )
    overlapping = {tuple(row) for row in rows}
    assert len(seen) == 1  # one correlated statement for every bucket
    assert overlapping == {(s, a, b) for s, a, b, hit in cases if hit}

    # The bulk read applies the same half-open rule to a window.
    for source, start, end, hit in cases:
        found = await overlapping_spans(db_session, [source], start, end)
        assert bool(found.get(source)) is hit, (source, start, end)


async def test_overlapping_spans_is_one_bulk_read(db_session: AsyncSession) -> None:
    one, two, three = await _sources(db_session, 3)
    await open_pause(db_session, [one, two], reason=REASON, starts_at=_at(0), now=NOW)
    await close_pause(db_session, [one], reason=REASON, observed_at=_at(10), bucket_seconds=300)
    await open_pause(db_session, [one], reason=REASON, starts_at=_at(30), now=NOW)

    seen = _statements(db_session)
    found = await overlapping_spans(db_session, [one, two, three], _at(5), _at(40))
    assert len(seen) == 1
    assert [(s.starts_at, s.ends_at) for s in found[one]] == [(_at(0), _at(10)), (_at(30), None)]
    assert [(s.starts_at, s.ends_at, s.reason) for s in found[two]] == [(_at(0), None, REASON)]
    assert three not in found


async def test_no_rows_on_staleness_or_none(db_session: AsyncSession) -> None:
    """The helpers write exactly what they are given, so a caller that sees a stale
    inventory or a `None` enabled passes nothing and no row (or statement) results."""
    (source,) = await _sources(db_session)
    seen = _statements(db_session)

    assert await open_pause(db_session, [], reason=REASON, starts_at=_at(0), now=NOW) == 0
    assert await close_pause(db_session, [], reason=REASON, observed_at=_at(0),
                             bucket_seconds=300) == 0
    assert await overlapping_spans(db_session, iter(()), _at(0), _at(5)) == {}
    assert seen == []
    assert await _spans(db_session) == []

    # A naive timestamp is refused before any statement runs.
    with pytest.raises(ValueError):
        await open_pause(db_session, [source], reason=REASON, starts_at=datetime(2026, 1, 1),
                         now=NOW)
    with pytest.raises(ValueError):
        await close_pause(db_session, [source], reason=REASON, observed_at=datetime(2026, 1, 1),
                          bucket_seconds=300)
    assert [s for s in seen if "INSERT" in s or "UPDATE" in s] == []
    assert await _spans(db_session) == []


