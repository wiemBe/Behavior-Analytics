def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str) -> Config:
    """Build a Config with no alembic.ini, so env.py's fileConfig cannot run."""
    cfg = Config()
    cfg.set_main_option("script_location", "alembic")
    cfg.set_main_option("sqlalchemy.url", sync_url)
    return cfg


@pytest.fixture
def migrated_db() -> Iterator[str]:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    command.upgrade(_alembic_config(sync_url), "head")
    try:
        yield sync_url
    finally:
        reset_public_schema(sync_url)


def _seed_source(conn: Any) -> uuid.UUID:
    instance, source = uuid.uuid4(), uuid.uuid4()
    conn.execute(
        text(
            "INSERT INTO qradar_instance (id, name, console_host, api_version, verify_ssl, "
            "provider_kind, mcp_enabled, enabled, status, consecutive_failures) "
            "VALUES (:i, 'lab', 'qradar.lab.local', '20.0', true, 'REST', false, true, "
            "'HEALTHY', 0)"
        ).bindparams(i=instance)
    )
    conn.execute(
        text(
            "INSERT INTO log_source (id, instance_id, qradar_id, name, enabled, criticality, "
            "monitoring_enabled, maintenance_mode, business_hours_only, business_hours_start, "
            "business_hours_end, business_days, timezone_name, custom_thresholds, first_seen_at) "
            "VALUES (:s, :i, 8, 'jdbc', true, 'MEDIUM', true, false, false, 8, 18, "
            "'[1,2,3,4,5]', 'UTC', '{}', now())"
        ).bindparams(s=source, i=instance)
    )
    return source


def _insert(
    conn: Any, source: uuid.UUID, reason: str, start: datetime, end: datetime | None
) -> None:
    conn.execute(
        text(
            "INSERT INTO log_source_pause (log_source_id, reason, starts_at, ends_at) "
            "VALUES (:s, :r, :a, :b)"
        ).bindparams(s=source, r=reason, a=start, b=end)
    )


def test_constraints_index_and_cascade(migrated_db: str) -> None:
    engine = create_engine(migrated_db, future=True)
    try:
        with engine.begin() as conn:
            source = _seed_source(conn)
            _insert(conn, source, REASON, _at(0), _at(10))

        def refused(statement: Any, name: str) -> None:
            with pytest.raises(IntegrityError, match=name), engine.begin() as conn:
                statement(conn)

        refused(lambda c: _insert(c, source, "ABSENT", _at(20), None), "reason_known")
        refused(lambda c: _insert(c, source, REASON, _at(20), _at(20)), "ends_after_start")
        refused(lambda c: _insert(c, source, REASON, _at(20), _at(19)), "ends_after_start")
        refused(lambda c: _insert(c, source, REASON, _at(0), None), "pk_log_source_pause")
        refused(lambda c: _insert(c, uuid.uuid4(), REASON, _at(20), None), "fk_log_source_pause")
        with engine.begin() as conn:
            _insert(conn, source, REASON, _at(30), None)  # one open span is fine
        refused(lambda c: _insert(c, source, REASON, _at(40), None), "uq_log_source_pause_open")
        with engine.begin() as conn:  # closed spans may stack freely
            _insert(conn, source, REASON, _at(50), _at(60))

        with engine.begin() as conn:
            conn.execute(text("DELETE FROM log_source"))
        with engine.connect() as conn:
            assert conn.execute(text("SELECT count(*) FROM log_source_pause")).scalar() == 0
    finally:
        engine.dispose()


def test_schema_upgrade_downgrade_upgrade_no_drift(migrated_db: str) -> None:
    cfg = _alembic_config(migrated_db)
    engine = create_engine(migrated_db, future=True)
    try:
        assert "log_source_pause" in inspect(engine).get_table_names()
        command.downgrade(cfg, "0075")
        assert "log_source_pause" not in inspect(engine).get_table_names()
        command.upgrade(cfg, "head")
        assert "log_source_pause" in inspect(engine).get_table_names()
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()


def _snapshot(sync_url: str) -> dict[str, list[tuple[Any, ...]]]:
    """Constraint bodies, index definitions and column shapes of `log_source_pause`."""
    engine = create_engine(sync_url, future=True)
    try:
        with engine.connect() as conn:
            return {
                "constraints": [
                    tuple(r)
                    for r in conn.execute(
                        text(
                            "SELECT co.conname, pg_get_constraintdef(co.oid) FROM pg_constraint co "
                            "JOIN pg_class c ON c.oid = co.conrelid "
                            "JOIN pg_namespace n ON n.oid = c.relnamespace "
                            "WHERE n.nspname = 'public' AND c.relname = 'log_source_pause' "
                            "ORDER BY 1"
                        )
                    )
                ],
                "indexes": [
                    tuple(r)
                    for r in conn.execute(
                        text(
                            "SELECT indexname, indexdef FROM pg_indexes "
                            "WHERE schemaname = 'public' AND tablename = 'log_source_pause' "
                            "ORDER BY 1"
                        )
                    )
                ],
                "columns": [
                    tuple(r)
                    for r in conn.execute(
                        text(
                            "SELECT column_name, data_type, character_maximum_length, "
                            "is_nullable, column_default FROM information_schema.columns "
                            "WHERE table_schema = 'public' AND table_name = 'log_source_pause' "
                            "ORDER BY 1"
                        )
                    )
                ],
            }
    finally:
        engine.dispose()


def test_model_and_migration_schema_parity() -> None:
    """create_all (the db_schema path) and Alembic must build the same table.

    A model CHECK that renders invalid SQL makes create_all raise (J1c1's
    double-wrapped failure_code check did); a valid but different body, name,
    index predicate or column shape fails the snapshot comparison.
    """
    sync_url = _sync_url()
    engine = create_engine(sync_url, future=True)
    try:
        reset_public_schema(sync_url)
        Base.metadata.create_all(engine)
        from_metadata = _snapshot(sync_url)

        reset_public_schema(sync_url)
        command.upgrade(_alembic_config(sync_url), "head")
        from_migration = _snapshot(sync_url)

        assert from_metadata == from_migration
        # Not vacuous: the table, its checks, its two indexes and no defaults exist.
        assert len(from_migration["columns"]) == 4
        assert {name for name, _ in from_migration["constraints"]} == {
            "ck_log_source_pause_ends_after_start",
            "ck_log_source_pause_reason_known",
            "fk_log_source_pause_log_source_id_log_source",
            "pk_log_source_pause",
        }
        assert {name for name, _ in from_migration["indexes"]} == {
            "ix_log_source_pause_source_starts",
            "pk_log_source_pause",
            "uq_log_source_pause_open",
        }
        assert all(column_default is None for *_, column_default in from_migration["columns"])
    finally:
        reset_public_schema(sync_url)
        engine.dispose()
