"""Migration 0061: entity mentions and the contributor backfill index."""

from __future__ import annotations

import pytest
from sqlalchemy import create_engine, text

from tests.integration.schema_reset import reset_public_schema
from tests.integration.test_migrations import _alembic_config, _sync_url, _table_exists

pytestmark = pytest.mark.integration


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def _index_exists(engine, name: str) -> bool:  # type: ignore[no-untyped-def]
    with engine.connect() as connection:
        return connection.scalar(
            text("SELECT to_regclass(:name)"), {"name": f"public.{name}"}
        ) is not None


def test_0061_round_trip_and_alembic_check(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(cfg, "0060")
        assert not _table_exists(engine, "entity_mention")
        assert not _index_exists(engine, "ix_entity_mention_lookup")
        assert not _index_exists(engine, "ix_explanation_contributor_dimension_value")

        command.upgrade(cfg, "0061")
        assert _table_exists(engine, "entity_mention")
        assert _index_exists(engine, "ix_entity_mention_lookup")
        assert _index_exists(engine, "ix_explanation_contributor_dimension_value")

        command.downgrade(cfg, "0060")
        assert not _table_exists(engine, "entity_mention")
        assert not _index_exists(engine, "ix_entity_mention_lookup")
        assert not _index_exists(engine, "ix_explanation_contributor_dimension_value")

        command.upgrade(cfg, "0061")
        assert _table_exists(engine, "entity_mention")
        assert _index_exists(engine, "ix_entity_mention_lookup")
        assert _index_exists(engine, "ix_explanation_contributor_dimension_value")
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected after the 0061 round trip:\n{exc}")
    finally:
        engine.dispose()
