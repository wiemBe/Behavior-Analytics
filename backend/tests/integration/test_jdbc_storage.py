def _columns(conn: Any, table: str) -> dict[str, tuple[str, int | None, str]]:
    rows = conn.execute(
        text(
            "SELECT column_name, data_type, character_maximum_length, is_nullable "
            "FROM information_schema.columns "
            "WHERE table_schema = 'public' AND table_name = :t"
        ).bindparams(t=table)
    )
    return {row[0]: (row[1], row[2], row[3]) for row in rows}


def test_only_safe_columns_and_fixed_states(clean_db: str) -> None:
    sync_url = clean_db
    engine = create_engine(sync_url, future=True)
    try:
        with engine.connect() as conn:
            config_columns = _columns(conn, "jdbc_source_config")
            sync_columns = _columns(conn, "jdbc_sync_state")
        assert set(config_columns) == _CONFIG_COLUMNS
        assert set(sync_columns) == _SYNC_COLUMNS
        assert not any(
            shape in name
            for name in config_columns
            for shape in _CREDENTIAL_SHAPES
        )
        assert config_columns["database_type"][:2] == ("character varying", 32)
        assert config_columns["database_host"][:2] == ("character varying", 253)
        assert config_columns["tls_hostname"][:2] == ("character varying", 253)
        assert config_columns["database_name"][:2] == ("character varying", 255)
        assert config_columns["schema_name"][:2] == ("character varying", 255)
        assert config_columns["table_name"][:2] == ("character varying", 255)
        assert config_columns["compare_field"][:2] == ("character varying", 255)
        assert config_columns["source_label"][:2] == ("character varying", 255)
        assert config_columns["select_list"][:2] == ("character varying", 2048)
        assert config_columns["predefined_query"][:2] == ("character varying", 128)
        assert config_columns["start_time_local"][:2] == ("character varying", 16)
        assert config_columns["failure_code"][:2] == ("character varying", 48)
        assert config_columns["config_state"][:2] == ("character varying", 24)
        assert config_columns["eps_throttle"][0] == "bigint"
        assert config_columns["field_states"][:2] == ("jsonb", None)
        assert config_columns["field_states"][2] == "NO"
        assert config_columns["observed_at"][:2] == ("timestamp with time zone", None)
        assert sync_columns["state"][:2] == ("character varying", 24)
        assert sync_columns["response_bytes"][0] == "bigint"
        assert sync_columns["fallback_resume_id"][0] == "bigint"
        assert sync_columns["attempt_id"][0] == "uuid"

        # Nullability of the mandatory columns, pinned here so a change made in
        # both the model and the migration cannot hide from the parity test.
        for column in (
            "protocol_type_id",
            "field_states",
            "allowlist_version",
            "config_state",
            "observed_at",
        ):
            assert config_columns[column][2] == "NO"
        assert config_columns["database_port"][2] == "YES"
        assert config_columns["failure_code"][2] == "YES"
        assert config_columns["last_success_at"][2] == "YES"
        assert sync_columns["state"][2] == "NO"
        for counter in ("pages", "rows", "failures", "elapsed_ms"):
            assert sync_columns[counter][2] == "NO"
        for column in ("response_bytes", "failed_page", "failure_code", "fallback_resume_id"):
            assert sync_columns[column][2] == "YES"

        with engine.begin() as conn:
            _seed_parents(conn)
            _seed_rows(conn)

        for column, value, check in _CONFIG_REFUSALS:
            assignment = "CAST(:v AS jsonb)" if column == "field_states" else ":v"
            with (
                pytest.raises(IntegrityError, match=check),
                engine.begin() as conn,
            ):
                conn.execute(
                    text(f"UPDATE jdbc_source_config SET {column} = {assignment}").bindparams(  # noqa: S608
                        v=value
                    )
                )
        for column, value, check in _SYNC_REFUSALS:
            with (
                pytest.raises(IntegrityError, match=check),
                engine.begin() as conn,
            ):
                conn.execute(
                    text(f"UPDATE jdbc_sync_state SET {column} = :v").bindparams(  # noqa: S608
                        v=value
                    )
                )

        # Both ends of each bound are accepted, and a JSON object is required
        # only as a coarse shape (the per-key rule is the pure validator's job).
        with engine.begin() as conn:
            conn.execute(
                text(
                    "UPDATE jdbc_source_config SET database_port = 1, "
                    "polling_interval_seconds = 1, eps_throttle = 0, allowlist_version = 1, "
                    "config_state = 'NOT_COLLECTED', failure_code = 'a', "
                    "field_states = CAST(:fs AS jsonb)"
                ).bindparams(fs='{"database_type": {"code": "SET", "reason": null}}')
            )
            conn.execute(
                text(
                    "UPDATE jdbc_sync_state SET state = 'UNSUPPORTED', response_bytes = 0, "
                    "failed_page = 0"
                )
            )
        with engine.connect() as conn:
            assert conn.execute(
                text(
                    "SELECT database_port, polling_interval_seconds, eps_throttle, "
                    "field_states -> 'database_type' ->> 'code' FROM jdbc_source_config"
                )
            ).one() == (1, 1, 0, "SET")
            assert conn.execute(
                text("SELECT state, response_bytes, failed_page FROM jdbc_sync_state")
            ).one() == ("UNSUPPORTED", 0, 0)
    finally:
        engine.dispose()


def test_constraints_and_cascade(clean_db: str) -> None:
    sync_url = clean_db
    engine = create_engine(sync_url, future=True)
    try:
        with engine.begin() as conn:
            _seed_parents(conn)
            _seed_rows(conn)

        # Deleting the source removes only its config row; the console's pass
        # state survives because it belongs to the instance.
        with engine.begin() as conn:
            conn.execute(text("DELETE FROM log_source"))
        with engine.connect() as conn:
            assert conn.execute(text("SELECT count(*) FROM jdbc_source_config")).scalar() == 0
            assert conn.execute(text("SELECT count(*) FROM jdbc_sync_state")).scalar() == 1

        with engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO log_source "
                    "(id, instance_id, qradar_id, name, enabled, criticality, monitoring_enabled, "
                    " maintenance_mode, business_hours_only, business_hours_start, "
                    " business_hours_end, business_days, timezone_name, custom_thresholds, "
                    " first_seen_at) "
                    "VALUES (CAST(:ls AS uuid), CAST(:i AS uuid), 8, 'jdbc', true, 'MEDIUM', true, "
                    "        false, false, 8, 18, '[1,2,3,4,5]', 'UTC', '{}', now())"
                ).bindparams(ls=SOURCE_ID, i=INSTANCE_ID)
            )
            conn.execute(
                text(
                    "INSERT INTO jdbc_source_config "
                    "(log_source_id, protocol_type_id, field_states, allowlist_version, "
                    " config_state, observed_at) "
                    "VALUES (CAST(:ls AS uuid), 8, '{}'::jsonb, 1, 'COMPLETE', now())"
                ).bindparams(ls=SOURCE_ID)
            )

        # Deleting the console cascades through log_source to the config row and
        # directly to the pass row.
        with engine.begin() as conn:
            conn.execute(text("DELETE FROM qradar_instance"))
        with engine.connect() as conn:
            assert conn.execute(text("SELECT count(*) FROM jdbc_source_config")).scalar() == 0
            assert conn.execute(text("SELECT count(*) FROM jdbc_sync_state")).scalar() == 0
    finally:
        engine.dispose()


def test_jdbc_migration_roundtrip_no_drift(clean_db: str) -> None:
    sync_url = clean_db
    cfg = _alembic_config(sync_url)
    engine = create_engine(sync_url, future=True)
    try:
        inspector = inspect(engine)
        assert {"jdbc_source_config", "jdbc_sync_state"} <= set(inspector.get_table_names())

        command.downgrade(cfg, "0074")
        inspector = inspect(engine)
        assert not {"jdbc_source_config", "jdbc_sync_state"} & set(inspector.get_table_names())

        command.upgrade(cfg, "head")
        inspector = inspect(engine)
        assert {"jdbc_source_config", "jdbc_sync_state"} <= set(inspector.get_table_names())

        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()


def _schema_snapshot(sync_url: str) -> tuple[list[tuple[Any, ...]], list[tuple[Any, ...]]]:
    """Every constraint definition and column shape of the two JDBC tables.

    ``pg_get_constraintdef`` returns the CHECK/FK/PK body without the name, so
    the short model constraint names and the ``ck_<table>_<name>`` migration
    names compare equal when the bodies do.
    """
    engine = create_engine(sync_url, future=True)
    try:
        with engine.connect() as conn:
            constraints = conn.execute(
                text(
                    "SELECT c.relname, pg_get_constraintdef(co.oid) "
                    "FROM pg_constraint co "
                    "JOIN pg_class c ON c.oid = co.conrelid "
                    "JOIN pg_namespace n ON n.oid = c.relnamespace "
                    "WHERE n.nspname = 'public' "
                    "AND c.relname IN ('jdbc_source_config', 'jdbc_sync_state') "
                    "ORDER BY 1, 2"
                )
            ).all()
            columns = conn.execute(
                text(
                    "SELECT table_name, column_name, data_type, character_maximum_length, "
                    "       is_nullable "
                    "FROM information_schema.columns "
                    "WHERE table_schema = 'public' "
                    "AND table_name IN ('jdbc_source_config', 'jdbc_sync_state') "
                    "ORDER BY 1, 2"
                )
            ).all()
        return constraints, columns
    finally:
        engine.dispose()


def test_model_and_migration_schema_parity() -> None:
    """create_all (the db_schema path) and alembic must build the same schema.

    A CREATE TABLE that renders an invalid CHECK makes create_all fail outright;
    a valid-but-different body is caught by the constraint snapshot comparison.
    """
    sync_url = _sync_url()
    engine = create_engine(sync_url, future=True)
    try:
        # Path 1: the ordinary db_schema fixture path, Base.metadata.create_all.
        reset_public_schema(sync_url)
        Base.metadata.create_all(engine)
        from_metadata = _schema_snapshot(sync_url)

        # Path 2: the migration.
        reset_public_schema(sync_url)
        command.upgrade(_alembic_config(sync_url), "head")
        from_migration = _schema_snapshot(sync_url)

        assert from_metadata == from_migration
    finally:
        reset_public_schema(sync_url)
        engine.dispose()


