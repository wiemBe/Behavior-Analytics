def _alembic_config(sync_url: str) -> Config:
    """Build a Config with no alembic.ini, so env.py's fileConfig cannot run."""
    cfg = Config()
    cfg.set_main_option("script_location", "alembic")
    cfg.set_main_option("sqlalchemy.url", sync_url)
    return cfg


