"""SOC-1c (D-55): migration 0056 adds STALE to the disposition CHECK and refuses to lose it."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

from tests.integration.schema_reset import reset_public_schema

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(
        "TEST_DATABASE_URL" not in os.environ,
        reason="set TEST_DATABASE_URL to run the stale triage migration test",
    ),
]

_INSERT = text(
    "INSERT INTO anomaly_triage (id, family, anomaly_id, status, disposition, "
    "updated_by, version) VALUES (gen_random_uuid(), 'waf', gen_random_uuid(), "
    "'CLOSED', :d, 'system', 1)"
)


@pytest.fixture
def clean_db() -> str:
    url = os.environ["TEST_DATABASE_URL"].replace("+asyncpg", "+psycopg")
    reset_public_schema(url)
    return url


def _cfg(url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    cfg = Config()
    cfg.set_main_option("script_location", "alembic")
    cfg.set_main_option("sqlalchemy.url", url)
    return cfg


def test_0056_round_trip_and_the_downgrade_refusal(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = _cfg(clean_db)
    command.upgrade(cfg, "0055")
    engine = create_engine(clean_db, future=True)
    try:
        # Before 0056 the closed set does not hold STALE.
        with pytest.raises(IntegrityError, match="disposition_known"), engine.begin() as conn:
            conn.execute(_INSERT, {"d": "STALE"})

        command.upgrade(cfg, "0056")
        with engine.begin() as conn:
            conn.execute(_INSERT, {"d": "NOISE"})
            conn.execute(_INSERT, {"d": "STALE"})
        with pytest.raises(IntegrityError, match="disposition_known"), engine.begin() as conn:
            conn.execute(_INSERT, {"d": "BOGUS"})

        # The downgrade refuses while a STALE row exists, and changes nothing.
        with pytest.raises(RuntimeError, match="STALE"):
            command.downgrade(cfg, "0055")
        with engine.connect() as conn:
            assert (
                conn.execute(
                    text("SELECT count(*) FROM anomaly_triage WHERE disposition = 'STALE'")
                ).scalar()
                == 1
            )
            version = conn.execute(text("SELECT version_num FROM alembic_version")).scalar()
        assert version == "0056"

        with engine.begin() as conn:
            conn.execute(text("DELETE FROM anomaly_triage WHERE disposition = 'STALE'"))
        command.downgrade(cfg, "0055")
        with pytest.raises(IntegrityError, match="disposition_known"), engine.begin() as conn:
            conn.execute(_INSERT, {"d": "STALE"})
        with engine.connect() as conn:  # the NOISE row survived the round trip
            assert conn.execute(text("SELECT count(*) FROM anomaly_triage")).scalar() == 1

        command.upgrade(cfg, "head")
        with engine.begin() as conn:
            conn.execute(_INSERT, {"d": "STALE"})
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
