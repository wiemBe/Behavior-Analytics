"""Migration 0057: the alert-policy tables and the widened e-mail template check.

Runs the real revision up, down and up again, refuses a downgrade that would
delete an administrator's digest template, and checks the constraints and the
absence of schema drift at head. DB-gated; no ``alembic.ini`` (AGENTS.md §4).
"""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

from tests.integration.schema_reset import reset_public_schema
from tests.integration.test_migrations import _alembic_config, _sync_url, _table_exists

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")

INSTANCE = "11111111-1111-1111-1111-111111111111"


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def _instance(conn) -> None:  # type: ignore[no-untyped-def]
    conn.execute(
        text(
            "INSERT INTO qradar_instance (id, name, console_host, api_version, "
            " verify_ssl, provider_kind, mcp_enabled, enabled, status, "
            " consecutive_failures) VALUES (CAST(:i AS uuid), 'lab', 'lab.local', "
            " '20.0', true, 'REST', false, true, 'HEALTHY', 0)"
        ).bindparams(i=INSTANCE)
    )


def test_0057_round_trip_constraints_and_drift(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    policy = (
        "INSERT INTO alert_policy (id, instance_id, scope_kind, scope_value, family, "
        " detector_type, mode) VALUES (gen_random_uuid(), {i}, '{scope}', '{value}', "
        " '{family}', {detector}, '{mode}')"
    )
    run = (
        "INSERT INTO alert_digest_run (id, instance_id, digest_date, state, item_count, "
        " recipient_count, error_code) VALUES (gen_random_uuid(), CAST(:i AS uuid), "
        " '{day}', '{state}', 0, 0, {error})"
    )
    template = (
        "INSERT INTO email_template (id, alert_type, subject, html_body, enabled) "
        "VALUES (gen_random_uuid(), '{kind}', 's', '<p>x</p>', true)"
    )
    try:
        command.upgrade(cfg, "0056")
        assert not _table_exists(engine, "alert_policy")
        assert not _table_exists(engine, "alert_digest_run")

        command.upgrade(cfg, "0057")
        assert _table_exists(engine, "alert_policy")
        assert _table_exists(engine, "alert_digest_run")

        with engine.begin() as conn:
            _instance(conn)
            conn.execute(
                text(policy.format(
                    i="NULL", scope="CLASS", value="FIREWALL",
                    family="log_source", detector="NULL", mode="DIGEST",
                ))
            )
            conn.execute(
                text(policy.format(
                    i=f"CAST('{INSTANCE}' AS uuid)", scope="SOURCE",
                    value="11111111-1111-1111-1111-111111111112",
                    family="waf", detector="'WAF_REQUEST_RATE_SPIKE'",
                    mode="RECORD_ONLY",
                ))
            )
            conn.execute(
                text(
                    run.format(day="2026-11-06", state="SUCCESS", error="NULL")
                ).bindparams(i=INSTANCE)
            )
            conn.execute(text(template.format(kind="digest")))

        refused = [
            policy.format(
                i="NULL", scope="CLASS", value="FIREWALL", family="log_source",
                detector="NULL", mode="DIGEST",
            ),  # NULL instance and NULL detector are one identity, not many
            policy.format(
                i="NULL", scope="NOPE", value="x", family="log_source",
                detector="NULL", mode="ALERT",
            ),
            policy.format(
                i="NULL", scope="CLASS", value="", family="log_source",
                detector="NULL", mode="ALERT",
            ),
            policy.format(
                i="NULL", scope="CLASS", value="x", family="NOPE",
                detector="NULL", mode="ALERT",
            ),
            policy.format(
                i="NULL", scope="CLASS", value="x", family="log_source",
                detector="''", mode="ALERT",
            ),
            policy.format(
                i="NULL", scope="CLASS", value="x", family="log_source",
                detector="NULL", mode="NOPE",
            ),
        ]
        for statement in refused:
            with pytest.raises(IntegrityError), engine.begin() as conn:
                conn.execute(text(statement))

        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(
                text(
                    run.format(day="2026-11-06", state="SUCCESS", error="NULL")
                ).bindparams(i=INSTANCE)
            )
        for state, error in (
            ("NOPE", "NULL"),
            ("FAILED", "'the relay said no'"),
        ):
            with pytest.raises(IntegrityError), engine.begin() as conn:
                conn.execute(
                    text(
                        run.format(day="2026-11-07", state=state, error=error)
                    ).bindparams(i=INSTANCE)
                )
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(
                text(policy.format(
                    i="CAST('99999999-9999-9999-9999-999999999999' AS uuid)",
                    scope="CLASS", value="IPS", family="log_source",
                    detector="NULL", mode="ALERT",
                ))
            )
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(template.format(kind="not_a_type")))

        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")

        # The downgrade refuses while a digest template exists, then restores the old list.
        with pytest.raises(RuntimeError, match="digest row"):
            command.downgrade(cfg, "0056")
        with engine.begin() as conn:
            conn.execute(text("DELETE FROM email_template WHERE alert_type = 'digest'"))
        command.downgrade(cfg, "0056")
        assert not _table_exists(engine, "alert_policy")
        assert not _table_exists(engine, "alert_digest_run")
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(template.format(kind="digest")))

        command.upgrade(cfg, "head")
        assert _table_exists(engine, "alert_policy")
        assert _table_exists(engine, "alert_digest_run")
        with engine.begin() as conn:
            conn.execute(text(template.format(kind="digest")))
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
