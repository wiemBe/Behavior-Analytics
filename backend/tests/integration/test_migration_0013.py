"""Migration 0013: round trip, seed rows, cadence CHECK and model drift."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    engine = create_engine(sync_url, future=True)
    with engine.begin() as connection:
        connection.execute(text("DROP SCHEMA public CASCADE"))
        connection.execute(text("CREATE SCHEMA public"))
    engine.dispose()
    return sync_url


def _exists(connection, table: str) -> bool:  # type: ignore[no-untyped-def]
    return bool(
        connection.execute(
            text("SELECT to_regclass(:table)").bindparams(table=f"public.{table}")
        ).scalar()
    )


def test_0013_round_trip_seed_check_and_no_drift(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "head")
        with engine.connect() as connection:
            rows = connection.execute(
                text(
                    "SELECT family, cadence_seconds, updated_at, last_run_at "
                    "FROM search_cadence ORDER BY family"
                )
            ).all()
            assert {row.family for row in rows} == {
                "PHASE_A_VOLUME",
                "WAF_COLLECTION",
                "ANOMALY_EXPLANATION",
                "RULE_MATCH",
            }
            assert all(row.cadence_seconds == 3600 for row in rows)
            assert all(row.updated_at is not None and row.last_run_at is None for row in rows)

        with (
            pytest.raises(IntegrityError, match="cadence_seconds_allowed"),
            engine.begin() as connection,
        ):
            connection.execute(
                text(
                    "UPDATE search_cadence SET cadence_seconds = 600 "
                    "WHERE family = 'ANOMALY_EXPLANATION'"
                )
            )

        command.downgrade(config, "0012")
        with engine.connect() as connection:
            assert not _exists(connection, "search_cadence")
            assert _exists(connection, "rule_match_window")

        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
