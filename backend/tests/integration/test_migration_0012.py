"""Migration 0012 (measured rule matches): round trip, hypertable, constraints.

Kept apart from `test_migrations.py` on purpose, so the parallel T-022 work and
this one never edit the same file. It is written against `head` and `-1` rather
than a revision number, so re-chaining 0012 behind another migration does not
break it.
"""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")
INSTANCE_ID = "dddddddd-0000-0000-0000-000000000001"


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):
    from alembic.config import Config

    cfg = Config()
    cfg.set_main_option("script_location", "alembic")
    cfg.set_main_option("sqlalchemy.url", sync_url)
    return cfg


@pytest.fixture
def clean_db() -> str:
    """Drop everything (including timescale-managed objects) before each test."""
    sync_url = _sync_url()
    engine = create_engine(sync_url, future=True)
    with engine.begin() as conn:
        conn.execute(text("DROP SCHEMA public CASCADE"))
        conn.execute(text("CREATE SCHEMA public"))
    engine.dispose()
    return sync_url


def _exists(conn, name: str) -> bool:
    query = text("SELECT to_regclass(:n)").bindparams(n=f"public.{name}")
    return bool(conn.execute(query).scalar())


def test_0012_round_trips_and_leaves_no_drift(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(cfg, "head")
        with engine.connect() as conn:
            assert _exists(conn, "rule_match_metric")
            assert _exists(conn, "rule_match_window")
            has_timescale = conn.execute(
                text("SELECT 1 FROM pg_extension WHERE extname = 'timescaledb'")
            ).scalar()
            if has_timescale:
                hypertables = {
                    row[0]
                    for row in conn.execute(
                        text("SELECT hypertable_name FROM timescaledb_information.hypertables")
                    )
                }
                assert "rule_match_metric" in hypertables
                assert "rule_match_window" not in hypertables
            # No backfill and no transient default may be left behind.
            leftovers = [
                row[0]
                for row in conn.execute(text(
                    "SELECT table_name || '.' || column_name FROM information_schema.columns "
                    "WHERE table_schema = 'public' AND column_default IS NOT NULL "
                    "  AND table_name IN ('rule_match_metric', 'rule_match_window')"
                ))
            ]
            assert not leftovers

        command.downgrade(cfg, "-1")
        with engine.connect() as conn:
            assert not _exists(conn, "rule_match_metric")
            assert not _exists(conn, "rule_match_window")
            assert _exists(conn, "analytics_rule")  # earlier tables are untouched

        command.upgrade(cfg, "head")
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()


def test_0012_constraints_reject_unknown_values(clean_db: str) -> None:
    from alembic import command

    cfg = _alembic_config(clean_db)
    command.upgrade(cfg, "head")
    engine = create_engine(clean_db, future=True)
    try:
        with engine.begin() as conn:
            conn.execute(text(
                "INSERT INTO qradar_instance (id, name, console_host, api_version, verify_ssl, "
                " provider_kind, mcp_enabled, enabled, status, consecutive_failures) "
                "VALUES (CAST(:i AS uuid), 'lab', 'qradar.lab.local', '20.0', true, 'REST', "
                " false, true, 'HEALTHY', 0)"
            ).bindparams(i=INSTANCE_ID))

        def window(status: str, rows: int = 0) -> None:
            with engine.begin() as conn:
                conn.execute(text(
                    "INSERT INTO rule_match_window (instance_id, window_start, window_seconds, "
                    " status, rows_returned, row_cap, unknown_ids, query_version, collected_at, "
                    " attempts) "
                    "VALUES (CAST(:i AS uuid), now(), 3600, :s, :r, 100, 0, 'v', now(), 1)"
                ).bindparams(i=INSTANCE_ID, s=status, r=rows))

        with pytest.raises(IntegrityError, match="status_known"):
            window("PARTIAL")
        with pytest.raises(IntegrityError, match="rows_returned_non_negative"):
            window("COMPLETE", rows=-1)
        window("COMPLETE")
    finally:
        engine.dispose()
