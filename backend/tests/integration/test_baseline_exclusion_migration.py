"""Migration 0064: baseline training exclusions and the two triage event kinds."""

from __future__ import annotations

import os
import uuid

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import DataError, IntegrityError

from tests.integration.schema_reset import reset_public_schema

pytestmark = pytest.mark.integration

_INSERT = (
    "INSERT INTO baseline_training_exclusion (id, origin_family, origin_anomaly_id, "
    "subject_kind, subject_id, scope_key, starts_at, ends_at, "
    "reason, created_by, revoked_by, revoked_at, revocation_reason) VALUES "
    "(:id, :fam, :anomaly, :kind, :subject, :scope, :start, :end, :reason, :by, "
    ":rby, :rat, :rreason)"
)
_GOOD = {
    "fam": "log_source",
    "anomaly": uuid.UUID(int=1),
    "kind": "log_source",
    "subject": uuid.UUID(int=2),
    "scope": "log_source:volume",
    "start": "2026-11-04 08:00+00",
    "end": "2026-11-04 10:00+00",
    "reason": "outage",
    "by": "alice",
    "rby": None,
    "rat": None,
    "rreason": None,
}


def _sync_url() -> str:
    value = os.environ.get("TEST_DATABASE_URL")
    if value is None:
        pytest.skip("TEST_DATABASE_URL is required")
    return value.replace("+asyncpg", "+psycopg")


def _config(url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", url)
    return config


def _insert(connection, **override):  # type: ignore[no-untyped-def]
    values = {**_GOOD, "id": uuid.uuid4(), **override}
    connection.execute(
        text(_INSERT),
        values,
    )


def _rejected(engine, **override) -> None:  # type: ignore[no-untyped-def]
    with pytest.raises(IntegrityError), engine.begin() as connection:
        _insert(connection, **override)


def _event_kind_check(connection) -> str:  # type: ignore[no-untyped-def]
    return connection.execute(
        text(
            "SELECT pg_get_constraintdef(oid) FROM pg_constraint "
            "WHERE conname = 'ck_anomaly_triage_event_kind_known'"
        )
    ).scalar_one()


def _insert_event(connection, triage_id, kind) -> None:  # type: ignore[no-untyped-def]
    connection.execute(
        text(
            "INSERT INTO anomaly_triage_event (id, triage_id, kind, actor, triage_version) "
            "VALUES (:id, :t, :k, 'alice', 1)"
        ),
        {"id": uuid.uuid4(), "t": triage_id, "k": kind},
    )


def test_0064_round_trip_checks_and_alembic_check() -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    url = _sync_url()
    reset_public_schema(url)
    config = _config(url)
    engine = create_engine(url, future=True)
    try:
        command.upgrade(config, "0063")
        with engine.connect() as connection:
            assert (
                connection.execute(
                    text("SELECT to_regclass('baseline_training_exclusion')")
                ).scalar()
                is None
            )
            assert "BASELINE_EXCLUSION" not in _event_kind_check(connection)

        command.upgrade(config, "0064")
        # `alembic check` needs the head revision, so the drift check runs after
        # the final `upgrade head` below; a later migration must not break this test.

        with engine.begin() as connection:
            _insert(connection)
        _rejected(engine, fam="nope")
        _rejected(engine, kind="nope")
        _rejected(engine, reason="   ")
        _rejected(engine, reason="")
        _rejected(engine, end="2026-11-04 08:00+00", scope="s1")
        _rejected(engine, end="2026-11-04 07:00+00", scope="s2")
        _rejected(engine, end="2026-11-11 08:00:01+00", scope="s3")
        with engine.begin() as connection:
            _insert(connection, end="2026-11-11 08:00+00", scope="exactly-seven-days")
        # Half-filled revocation, each way.
        _rejected(engine, rby="bob", scope="r1")
        _rejected(engine, rat="2026-11-05 08:00+00", scope="r2")
        _rejected(engine, rreason="why", scope="r3")
        _rejected(engine, rby="bob", rat="2026-11-05 08:00+00", scope="r4")
        _rejected(engine, rby="bob", rat="2026-11-05 08:00+00", rreason="  ", scope="r5")

        # Active exact duplicate is rejected; it is allowed once the first is revoked.
        _rejected(engine)
        with engine.begin() as connection:
            connection.execute(
                text(
                    "UPDATE baseline_training_exclusion SET revoked_by = 'bob', "
                    "revoked_at = now(), revocation_reason = 'mistake' WHERE scope_key = "
                    "'log_source:volume'"
                )
            )
            _insert(connection)
        # A different interval on the same subject is fine.
        with engine.begin() as connection:
            _insert(connection, start="2026-11-04 10:00+00", end="2026-11-04 11:00+00")

        # The two new triage event kinds.
        triage_id = uuid.uuid4()
        with engine.begin() as connection:
            connection.execute(
                text(
                    "INSERT INTO anomaly_triage "
                    "(id, family, anomaly_id, status, version, updated_by) "
                    "VALUES (:id, 'log_source', :a, 'NEW', 1, 'alice')"
                ),
                {"id": triage_id, "a": uuid.uuid4()},
            )
            _insert_event(connection, triage_id, "BASELINE_EXCLUSION_CREATED")
            _insert_event(connection, triage_id, "BASELINE_EXCLUSION_REVOKED")
        with pytest.raises(IntegrityError), engine.begin() as connection:
            _insert_event(connection, triage_id, "BASELINE_EXCLUSION_OTHER")

        command.downgrade(config, "0063")
        with engine.connect() as connection:
            assert (
                connection.execute(
                    text("SELECT to_regclass('baseline_training_exclusion')")
                ).scalar()
                is None
            )
            assert "BASELINE_EXCLUSION" not in _event_kind_check(connection)
            remaining = connection.execute(
                text("SELECT kind FROM anomaly_triage_event")
            ).scalars().all()
            assert remaining == []
        # The narrowed column and the old check both refuse the new kinds.
        with pytest.raises((IntegrityError, DataError)), engine.begin() as connection:
            _insert_event(connection, triage_id, "BASELINE_EXCLUSION_CREATED")

        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover
            pytest.fail(f"alembic check reports drift: {exc}")
        with engine.begin() as connection:
            _insert_event(connection, triage_id, "BASELINE_EXCLUSION_CREATED")
    finally:
        engine.dispose()
