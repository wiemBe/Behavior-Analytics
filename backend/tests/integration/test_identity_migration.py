"""Migration 0068: identity tables round-trip, checks, hypertables, no drift.

The round trip is ``upgrade 0068``, ``downgrade 0067``, ``upgrade 0068``.
The version asserted is 0068. ``alembic check`` runs only after ``upgrade head``
(FIX-54), so a later head does not make this test treat itself as head.
"""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.exc import DataError, IntegrityError

from tests.integration.schema_reset import reset_public_schema

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif("TEST_DATABASE_URL" not in os.environ, reason="set TEST_DATABASE_URL"),
]

INSTANCE = "11111111-1111-1111-1111-111111111111"
SOURCE = "22222222-2222-2222-2222-222222222222"
SOURCE_B = "33333333-3333-3333-3333-333333333333"
SOURCE_C = "44444444-4444-4444-4444-444444444444"
TABLES = (
    "identity_source_profile",
    "identity_bucket",
    "identity_event_count",
    "identity_top_username",
)
HYPERTABLES = ("identity_bucket", "identity_event_count", "identity_top_username")
WHEN = "2026-11-13 12:00:00+00"


def _sync_url() -> str:
    return os.environ["TEST_DATABASE_URL"].replace("+asyncpg", "+psycopg")


def _config():  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", _sync_url())
    return config


def _version(engine) -> str:  # type: ignore[no-untyped-def]
    with engine.connect() as conn:
        return str(conn.execute(text("SELECT version_num FROM alembic_version")).scalar_one())


def _seed(conn) -> None:  # type: ignore[no-untyped-def]
    conn.execute(
        text(
            "INSERT INTO qradar_instance (id, name, console_host, api_version, verify_ssl, "
            "provider_kind, mcp_enabled, enabled, status, consecutive_failures) "
            "VALUES (CAST(:instance AS uuid), 'lab', 'qradar.lab.local', '20.0', true, "
            "'REST', false, true, 'HEALTHY', 0)"
        ),
        {"instance": INSTANCE},
    )
    insert_source = text(
        "INSERT INTO log_source (id, instance_id, qradar_id, name, enabled, criticality, "
        "monitoring_enabled, maintenance_mode, business_hours_only, business_hours_start, "
        "business_hours_end, business_days, timezone_name, custom_thresholds, first_seen_at) "
        "VALUES (CAST(:source AS uuid), CAST(:instance AS uuid), :qradar_id, :name, true, "
        "'MEDIUM', true, false, false, 8, 18, CAST('[1,2,3,4,5]' AS jsonb), 'UTC', "
        "CAST('{}' AS jsonb), now())"
    )
    for source, qradar_id, name in (
        (SOURCE, 17, "dc01"),
        (SOURCE_B, 18, "dc02"),
        (SOURCE_C, 19, "dc03"),
    ):
        conn.execute(
            insert_source,
            {"instance": INSTANCE, "source": source, "qradar_id": qradar_id, "name": name},
        )


def test_0068_round_trip_checks_hypertables_and_alembic_check() -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    url = _sync_url()
    reset_public_schema(url)
    config = _config()
    engine = create_engine(url, future=True)
    try:
        command.upgrade(config, "0067")
        names = set(inspect(engine).get_table_names())
        assert not set(TABLES) & names

        command.upgrade(config, "0068")
        assert _version(engine) == "0068"
        names = set(inspect(engine).get_table_names())
        assert set(TABLES) <= names
        with engine.connect() as conn:
            extension = conn.execute(
                text("SELECT 1 FROM pg_extension WHERE extname = 'timescaledb'")
            ).scalar()
            if extension:
                hypertables = {
                    row[0]
                    for row in conn.execute(
                        text("SELECT hypertable_name FROM timescaledb_information.hypertables")
                    )
                }
                assert set(HYPERTABLES) <= hypertables
                retention = conn.execute(
                    text(
                        "SELECT count(*) FROM timescaledb_information.jobs "
                        "WHERE proc_name IN ('policy_retention', 'policy_compression') "
                        "AND hypertable_name LIKE 'identity\\_%'"
                    )
                ).scalar()
                assert retention == 0

        command.downgrade(config, "0067")
        assert not set(TABLES) & set(inspect(engine).get_table_names())

        command.upgrade(config, "0068")
        assert _version(engine) == "0068"

        with engine.begin() as conn:
            _seed(conn)
            conn.execute(
                text(
                    "INSERT INTO identity_source_profile (id, instance_id, log_source_id, "
                    "enabled, profile_version, event_id_property, username_property, "
                    "enabled_event_ids, validation_status, validation_report) "
                    "VALUES (gen_random_uuid(), CAST(:instance AS uuid), CAST(:source AS uuid), "
                    "false, 1, 'EventID', 'username', "
                    "CAST('[4625,4740,4720,4726,4728,4732,4756,1102]' AS jsonb), "
                    "'UNVALIDATED', CAST('{}' AS jsonb))"
                ),
                {"instance": INSTANCE, "source": SOURCE},
            )
            conn.execute(
                text(
                    "INSERT INTO identity_bucket (log_source_id, bucket_start, bucket_seconds, "
                    "catalog_version, measurement, population, admission_truncated, "
                    "query_provenance, collected_at) VALUES (CAST(:source AS uuid), "
                    "CAST(:at AS timestamptz), 300, 1, 'EXACT', 1, false, "
                    "CAST('{}' AS jsonb), now())"
                ),
                {"source": SOURCE, "at": WHEN},
            )
            conn.execute(
                text(
                    "INSERT INTO identity_event_count (log_source_id, event_id, bucket_start, "
                    "event_count, measurement, names_measurement, admission_truncated) "
                    "VALUES (CAST(:source AS uuid), 1102, CAST(:at AS timestamptz), 1, "
                    "'EXACT', 'EXACT', false)"
                ),
                {"source": SOURCE, "at": WHEN},
            )
            conn.execute(
                text(
                    "INSERT INTO identity_top_username (log_source_id, event_id, bucket_start, "
                    "rank, username, truncated, event_count) VALUES (CAST(:source AS uuid), "
                    "1102, CAST(:at AS timestamptz), 1, 'auditor', false, 1)"
                ),
                {"source": SOURCE, "at": WHEN},
            )

        refused = (
            (
                "INSERT INTO identity_top_username (log_source_id, event_id, bucket_start, "
                "rank, username, truncated, event_count) VALUES (CAST(:source AS uuid), "
                "4625, CAST(:at AS timestamptz), 1, 'one-off', false, 2)",
                IntegrityError,
            ),
            (
                "INSERT INTO identity_top_username (log_source_id, event_id, bucket_start, "
                "rank, username, truncated, event_count) VALUES (CAST(:source AS uuid), "
                "1102, CAST(:at AS timestamptz), 21, 'past-n', false, 1)",
                IntegrityError,
            ),
            (
                "INSERT INTO identity_top_username (log_source_id, event_id, bucket_start, "
                "rank, username, truncated, event_count) VALUES (CAST(:source AS uuid), "
                "4624, CAST(:at AS timestamptz), 1, 'success', false, 4)",
                IntegrityError,
            ),
            (
                "INSERT INTO identity_top_username (log_source_id, event_id, bucket_start, "
                "rank, username, truncated, event_count) VALUES (CAST(:source AS uuid), "
                "1102, CAST(:at AS timestamptz), 2, '', false, 1)",
                IntegrityError,
            ),
            (
                "INSERT INTO identity_event_count (log_source_id, event_id, bucket_start, "
                "event_count, measurement, names_measurement, admission_truncated) "
                "VALUES (CAST(:source AS uuid), 4720, CAST(:at AS timestamptz), 0, "
                "'NOT_COLLECTED', 'NOT_COLLECTED', false)",
                IntegrityError,
            ),
            (
                "INSERT INTO identity_event_count (log_source_id, event_id, bucket_start, "
                "event_count, measurement, names_measurement, admission_truncated) "
                "VALUES (CAST(:source AS uuid), 4720, CAST(:at AS timestamptz), NULL, "
                "'EXACT', 'EXACT', false)",
                IntegrityError,
            ),
            (
                "INSERT INTO identity_bucket (log_source_id, bucket_start, bucket_seconds, "
                "catalog_version, measurement, population, admission_truncated, "
                "query_provenance, collected_at) VALUES (CAST(:source AS uuid), "
                "CAST(:at AS timestamptz) + interval '5 minutes', 300, 0, 'EXACT', 0, false, "
                "CAST('{}' AS jsonb), now())",
                IntegrityError,
            ),
            (
                "INSERT INTO identity_bucket (log_source_id, bucket_start, bucket_seconds, "
                "catalog_version, measurement, population, admission_truncated, "
                "query_provenance, collected_at) VALUES (CAST(:source AS uuid), "
                "CAST(:at AS timestamptz) + interval '10 minutes', 300, 1, 'HEALTHY', 0, "
                "false, CAST('{}' AS jsonb), now())",
                IntegrityError,
            ),
            (
                "INSERT INTO identity_source_profile (id, instance_id, log_source_id, enabled, "
                "profile_version, event_id_property, username_property, enabled_event_ids, "
                "validation_status, validation_report) VALUES (gen_random_uuid(), "
                "CAST(:instance AS uuid), CAST(:source_b AS uuid), false, 0, 'EventID', "
                "'username', CAST('[]' AS jsonb), 'UNVALIDATED', CAST('{}' AS jsonb))",
                IntegrityError,
            ),
            (
                "INSERT INTO identity_source_profile (id, instance_id, log_source_id, enabled, "
                "profile_version, event_id_property, username_property, enabled_event_ids, "
                "validation_status, validation_report) VALUES (gen_random_uuid(), "
                "CAST(:instance AS uuid), CAST(:source_c AS uuid), false, 1, 'EventID', "
                "'username', CAST('[]' AS jsonb), 'MAYBE', CAST('{}' AS jsonb))",
                IntegrityError,
            ),
        )
        for statement, error in refused:
            with pytest.raises(error), engine.begin() as conn:
                conn.execute(
                    text(statement),
                    {
                        "source": SOURCE,
                        "source_b": SOURCE_B,
                        "source_c": SOURCE_C,
                        "at": WHEN,
                        "instance": INSTANCE,
                    },
                )

        with pytest.raises((IntegrityError, DataError)), engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO identity_top_username (log_source_id, event_id, bucket_start, "
                    "rank, username, truncated, event_count) VALUES (CAST(:source AS uuid), "
                    "1102, CAST(:at AS timestamptz), 3, :name, false, 1)"
                ),
                {"source": SOURCE, "at": WHEN, "name": "B" * 256},
            )

        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover
            pytest.fail(f"schema drift detected:\n{exc}")
    finally:
        engine.dispose()
