"""Migration 0063: immutable shift handover records."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text

from tests.integration.schema_reset import reset_public_schema

pytestmark = pytest.mark.integration


def _sync_url() -> str:
    value = os.environ.get("TEST_DATABASE_URL")
    if value is None:
        pytest.skip("TEST_DATABASE_URL is required")
    return value.replace("+asyncpg", "+psycopg")


def _config(url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", url)
    return config


def test_0063_round_trip_and_alembic_check() -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    url = _sync_url()
    reset_public_schema(url)
    config = _config(url)
    engine = create_engine(url, future=True)
    try:
        command.upgrade(config, "0062")
        with engine.connect() as connection:
            assert connection.execute(text("SELECT to_regclass('shift_handover')")).scalar() is None

        command.upgrade(config, "0063")
        with engine.connect() as connection:
            columns = {
                row.column_name: (row.data_type, row.is_nullable, row.column_default)
                for row in connection.execute(
                    text(
                        "SELECT column_name, data_type, is_nullable, column_default "
                        "FROM information_schema.columns WHERE table_name = 'shift_handover'"
                    )
                )
            }
            assert set(columns) == {
                "id",
                "author_subject",
                "written_at",
                "window_started_at",
                "previous_id",
                "note",
                "body",
            }
            assert all(default is None for _kind, _nullable, default in columns.values())
            delete_rule = connection.execute(
                text(
                    "SELECT delete_rule FROM information_schema.referential_constraints "
                    "WHERE constraint_name = "
                    "'fk_shift_handover_previous_id_shift_handover'"
                )
            ).scalar_one()
            assert delete_rule == "SET NULL"
            definition = connection.execute(
                text(
                    "SELECT indexdef FROM pg_indexes WHERE tablename = 'shift_handover' "
                    "AND indexname = 'ix_shift_handover_written_at'"
                )
            ).scalar_one()
            assert "written_at DESC" in definition

        command.downgrade(config, "0062")
        with engine.connect() as connection:
            assert connection.execute(text("SELECT to_regclass('shift_handover')")).scalar() is None
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected after the 0063 round trip:\n{exc}")
    finally:
        engine.dispose()
