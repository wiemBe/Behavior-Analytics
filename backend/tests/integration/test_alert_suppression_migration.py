"""Migration 0058: time-boxed suppressions, hits, constraints and drift.

Runs the real revision up, down and up again without ``alembic.ini`` so the
process-wide logging configuration is untouched (AGENTS.md §4). DB-gated.
"""

from __future__ import annotations

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

from tests.integration.schema_reset import reset_public_schema
from tests.integration.test_migrations import _alembic_config, _sync_url, _table_exists

pytestmark = pytest.mark.integration


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


_SUPPRESSION_SQL = (
    "INSERT INTO alert_suppression (id, family, subject_id, detector_type, kind, "
    "reason, owner, starts_at, ends_at, reference, created_by) VALUES "
    "(gen_random_uuid(), '{family}', '{subject}', {detector}, '{kind}', "
    "'operator note', 'analyst', '{start}', '{end}', {reference}, 'analyst')"
)


def _suppression(
    *,
    subject: str = "11111111-1111-1111-1111-111111111111",
    detector: str | None = "VOLUME_SPIKE",
    kind: str = "ANALYST",
    reference: str | None = None,
    start: str = "2026-11-01 00:00+00",
    end: str = "2026-11-08 00:00+00",
    family: str = "log_source",
) -> str:
    detector_sql = "NULL" if detector is None else "'" + detector + "'"
    reference_sql = "NULL" if reference is None else "'" + reference + "'"
    return _SUPPRESSION_SQL.format(
        family=family,
        subject=subject,
        detector=detector_sql,
        kind=kind,
        start=start,
        end=end,
        reference=reference_sql,
    )


def test_0058_round_trip_constraints_cascade_and_drift(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(cfg, "0057")
        assert not _table_exists(engine, "alert_suppression")
        assert not _table_exists(engine, "alert_suppression_hit")

        command.upgrade(cfg, "0058")
        assert _table_exists(engine, "alert_suppression")
        assert _table_exists(engine, "alert_suppression_hit")

        with engine.begin() as conn:
            conn.execute(text(_suppression()))
            conn.execute(text(_suppression(detector=None)))
            conn.execute(
                text(
                    _suppression(
                        subject="44444444-4444-4444-4444-444444444444",
                        kind="KNOWN_CHANGE",
                        reference="CHG-123",
                        end="2026-12-01 00:00+00",
                    )
                )
            )

        refused = [
            # A second open row over the same non-NULL condition.
            _suppression(),
            # NULLS NOT DISTINCT makes the whole-source condition unique too.
            _suppression(detector=None),
            # More than thirty days, a zero-length window and a missing ticket.
            _suppression(
                subject="33333333-3333-3333-3333-333333333331",
                end="2026-12-02 00:00+00",
            ),
            _suppression(
                subject="33333333-3333-3333-3333-333333333332",
                end="2026-11-01 00:00+00",
            ),
            _suppression(
                subject="33333333-3333-3333-3333-333333333333",
                kind="KNOWN_CHANGE",
            ),
            _suppression(
                subject="33333333-3333-3333-3333-333333333334",
                family="not-a-family",
            ),
        ]
        for statement in refused:
            with pytest.raises(IntegrityError), engine.begin() as conn:
                conn.execute(text(statement))

        # One hit per incident and cascade are database guarantees, not service habits.
        with engine.begin() as conn:
            suppression_id = conn.execute(
                text(
                    "SELECT id FROM alert_suppression "
                    "WHERE subject_id = '11111111-1111-1111-1111-111111111111' "
                    "AND detector_type = 'VOLUME_SPIKE'"
                )
            ).scalar_one()
        hit = text(
            "INSERT INTO alert_suppression_hit (id, suppression_id, family, anomaly_id, "
            "detector_type, bucket_start, occurred_at) VALUES (gen_random_uuid(), "
            ":suppression_id, 'log_source', "
            "'22222222-2222-2222-2222-222222222222', 'VOLUME_SPIKE', "
            "'2026-11-02 00:00+00', '2026-11-02 00:01+00')"
        ).bindparams(suppression_id=suppression_id)
        with engine.begin() as conn:
            conn.execute(hit)
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(hit)
        with engine.begin() as conn:
            conn.execute(
                text("DELETE FROM alert_suppression WHERE detector_type = 'VOLUME_SPIKE'")
            )
            assert conn.execute(
                text("SELECT count(*) FROM alert_suppression_hit")
            ).scalar_one() == 0

        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")

        command.downgrade(cfg, "0057")
        assert not _table_exists(engine, "alert_suppression")
        assert not _table_exists(engine, "alert_suppression_hit")
        command.upgrade(cfg, "head")
        assert _table_exists(engine, "alert_suppression")
        assert _table_exists(engine, "alert_suppression_hit")
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected after the round trip:\n{exc}")
    finally:
        engine.dispose()
