"""Migration 0019: additive outage alert policy, round trip and no drift.

Pinned to its own revision so a later migration on top of it cannot change what
this test asserts. `0019`'s `down_revision` is `0017` for now, because a
parallel task (T-050b) adds `0018` on the same parent and the orchestrator
re-chains at merge.
"""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    engine = create_engine(sync_url, future=True)
    with engine.begin() as connection:
        connection.execute(text("DROP SCHEMA public CASCADE"))
        connection.execute(text("CREATE SCHEMA public"))
    engine.dispose()
    return sync_url


def _exists(connection, table: str) -> bool:  # type: ignore[no-untyped-def]
    return bool(
        connection.execute(
            text("SELECT to_regclass(:table)").bindparams(table=f"public.{table}")
        ).scalar()
    )


def _insert(connection, **overrides: object) -> None:  # type: ignore[no-untyped-def]
    values: dict[str, object] = {
        "instance_id": None,
        "scope_kind": "CLASS",
        "scope_value": "FIREWALL",
        "mode": "ALERT",
        "silence_grace_buckets": None,
    }
    values.update(overrides)
    connection.execute(
        text(
            "INSERT INTO outage_alert_policy "
            "(id, instance_id, scope_kind, scope_value, mode, silence_grace_buckets) "
            "VALUES (gen_random_uuid(), :instance_id, :scope_kind, :scope_value, "
            ":mode, :silence_grace_buckets)"
        ),
        values,
    )


def test_0019_round_trip_constraints_and_no_drift(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "0019")
        with engine.connect() as connection:
            assert _exists(connection, "outage_alert_policy")
            columns = {
                row.column_name: (row.data_type, row.is_nullable)
                for row in connection.execute(
                    text(
                        "SELECT column_name, data_type, is_nullable "
                        "FROM information_schema.columns "
                        "WHERE table_name = 'outage_alert_policy'"
                    )
                )
            }
            assert columns == {
                "instance_id": ("uuid", "YES"),
                "scope_kind": ("character varying", "NO"),
                "scope_value": ("character varying", "NO"),
                "mode": ("character varying", "NO"),
                "silence_grace_buckets": ("integer", "YES"),
                "updated_by": ("character varying", "YES"),
                "id": ("uuid", "NO"),
                "created_at": ("timestamp with time zone", "NO"),
                "updated_at": ("timestamp with time zone", "NO"),
            }
            unique_columns = connection.execute(
                text(
                    "SELECT array_agg(att.attname ORDER BY ordinality) AS columns "
                    "FROM pg_constraint con "
                    "JOIN unnest(con.conkey) WITH ORDINALITY AS key(attnum, ordinality) "
                    "ON true JOIN pg_attribute att ON att.attrelid = con.conrelid "
                    "AND att.attnum = key.attnum "
                    "WHERE con.conrelid = 'outage_alert_policy'::regclass "
                    "AND con.contype = 'u' GROUP BY con.oid"
                )
            ).scalar_one()
            assert unique_columns == ["instance_id", "scope_kind", "scope_value"]
            checks = {
                row[0]
                for row in connection.execute(
                    text(
                        "SELECT conname FROM pg_constraint "
                        "WHERE conrelid = 'outage_alert_policy'::regclass AND contype = 'c'"
                    )
                )
            }
            assert checks == {
                "ck_outage_alert_policy_scope_kind_known",
                "ck_outage_alert_policy_mode_known",
                "ck_outage_alert_policy_silence_grace_buckets_range",
            }
            cascades = {
                row.column_name: row.delete_rule
                for row in connection.execute(
                    text(
                        "SELECT kcu.column_name, rc.delete_rule "
                        "FROM information_schema.referential_constraints rc "
                        "JOIN information_schema.key_column_usage kcu "
                        "ON kcu.constraint_name = rc.constraint_name "
                        "WHERE kcu.table_name = 'outage_alert_policy'"
                    )
                )
            }
            assert cascades == {"instance_id": "CASCADE"}

        # A global row (instance_id NULL), then a second global row with the same
        # scope: uniqueness must reject it, which proves NULLS NOT DISTINCT.
        with engine.begin() as connection:
            _insert(connection, scope_value="FIREWALL", mode="ALERT")
        with pytest.raises(IntegrityError), engine.begin() as connection:
            _insert(connection, scope_value="FIREWALL", mode="RECORD_ONLY")

        # A SOURCE row for the same class value is a different scope, so allowed.
        with engine.begin() as connection:
            _insert(connection, scope_kind="SOURCE", scope_value="FIREWALL")
        # The CHECK constraints reject each bad field. One failing insert per
        # transaction: Postgres aborts the transaction on the first error.
        for bad in (
            {"scope_kind": "NOPE"},
            {"mode": "NOPE"},
            {"silence_grace_buckets": 49},
            {"silence_grace_buckets": -1},
        ):
            with pytest.raises(IntegrityError), engine.begin() as connection:
                _insert(connection, **bad)

        command.downgrade(config, "0017")
        with engine.connect() as connection:
            assert not _exists(connection, "outage_alert_policy")

        command.upgrade(config, "0019")
        with engine.connect() as connection:
            assert _exists(connection, "outage_alert_policy")
        # Drift is checked at head, so a later migration cannot hide a model gap.
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
