"""Migration 0018: IPS collection schema, cadence seed, round trip and drift."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text

from tests.integration.schema_reset import reset_public_schema

pytestmark = pytest.mark.integration
TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _config(url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", url)
    return config


@pytest.fixture
def clean_db() -> str:
    url = _sync_url()
    reset_public_schema(url)
    return url


def test_0018_round_trip_hypertables_seed_and_no_drift(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _config(clean_db)
    engine = create_engine(clean_db)
    try:
        command.upgrade(config, "0018")
        with engine.connect() as connection:
            tables = {
                connection.execute(text("SELECT to_regclass(:name)"), {"name": name}).scalar()
                for name in ("ips_source_bucket", "ips_entity", "ips_entity_metric")
            }
            assert None not in tables
            assert connection.execute(
                text(
                    "SELECT cadence_seconds FROM search_cadence "
                    "WHERE family = 'IPS_COLLECTION'"
                )
            ).scalar_one() == 3600
            extension = connection.execute(
                text("SELECT 1 FROM pg_extension WHERE extname = 'timescaledb'")
            ).scalar()
            if extension:
                hypertables = {
                    row[0]
                    for row in connection.execute(
                        text(
                            "SELECT hypertable_name FROM timescaledb_information.hypertables"
                        )
                    )
                }
                assert {"ips_source_bucket", "ips_entity_metric"} <= hypertables
        command.downgrade(config, "0017")
        with engine.connect() as connection:
            assert connection.execute(
                text("SELECT to_regclass('public.ips_source_bucket')")
            ).scalar() is None
            assert connection.execute(
                text("SELECT count(*) FROM search_cadence WHERE family = 'IPS_COLLECTION'")
            ).scalar_one() == 0
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover
            pytest.fail(f"schema drift detected:\n{exc}")
    finally:
        engine.dispose()
