"""Migration 0016: additive rule capacity history, round trip and no drift."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    engine = create_engine(sync_url, future=True)
    with engine.begin() as connection:
        connection.execute(text("DROP SCHEMA public CASCADE"))
        connection.execute(text("CREATE SCHEMA public"))
    engine.dispose()
    return sync_url


def _exists(connection, table: str) -> bool:  # type: ignore[no-untyped-def]
    return bool(
        connection.execute(
            text("SELECT to_regclass(:table)").bindparams(table=f"public.{table}")
        ).scalar()
    )


def test_0016_round_trip_and_no_drift(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "head")
        with engine.connect() as connection:
            assert _exists(connection, "rule_capacity_sample")
            columns = {
                row.column_name: row.is_nullable
                for row in connection.execute(
                    text(
                        "SELECT column_name, is_nullable FROM information_schema.columns "
                        "WHERE table_name = 'rule_capacity_sample'"
                    )
                )
            }
            assert columns == {
                "rule_id": "NO",
                "capacity_timestamp": "NO",
                "average_capacity": "YES",
                "base_capacity": "YES",
                "base_host_id": "YES",
                "recorded_at": "NO",
            }

        command.downgrade(config, "0014")
        with engine.connect() as connection:
            assert not _exists(connection, "rule_capacity_sample")
            assert _exists(connection, "anomaly_evaluation_watermark")

        command.upgrade(config, "head")
        with engine.connect() as connection:
            assert _exists(connection, "rule_capacity_sample")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
