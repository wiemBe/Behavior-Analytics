@pytest_asyncio.fixture
async def api(db_schema):  # type: ignore[no-untyped-def]
    engine = create_async_engine(db_schema)
    maker = async_sessionmaker(engine, expire_on_commit=False)
    app = create_app()
    base = Settings(_env_file=None).model_copy(update=dict.fromkeys(FEATURE_KEYS, False))
    principal = Principal("operator", permissions=frozenset({"admin:*"}))

    async def sessions():
        async with maker() as session:
            try:
                yield session
                await session.commit()
            except Exception:
                await session.rollback()
                raise

    app.dependency_overrides[get_session] = sessions
    app.dependency_overrides[get_settings] = lambda: base
    app.dependency_overrides[get_principal] = lambda: principal
    limiter.reset()
    async with httpx.AsyncClient(
        transport=httpx.ASGITransport(app), base_url="http://test"
    ) as client:
        yield client, app
    limiter.reset()
    await engine.dispose()


def _switch(body: dict, key: str) -> dict:
    return next(r["switches"][key] for r in body["families"] if key in r["switches"])


@pytest.mark.parametrize("key", NEW_KEYS)
async def test_default_off_and_audited_put_reset_through_the_route(api, db_session, key) -> None:
    client, _ = api

    body = (await client.get(URL)).json()
    switch = _switch(body, key)
    assert switch["enabled"] is False
    assert switch["source"] in {"env", "default"}

    for _ in range(2):
        assert (await client.put(f"{URL}/{key}", json={"enabled": True})).status_code == 204
    body = (await client.get(URL)).json()
    switch = _switch(body, key)
    assert switch["enabled"] is True
    assert switch["source"] == "db"
    assert switch["updated_by"] == "operator"
    assert switch["updated_at"]

    logs = (await db_session.scalars(select(AuditLog))).all()
    assert len(logs) == 1
    assert (logs[0].action, logs[0].actor, logs[0].object_type) == (
        "feature_switch.update", "operator", "feature_switch"
    )
    assert logs[0].object_id == key
    assert logs[0].detail["old"] is False and logs[0].detail["new"] is True

    for _ in range(2):
        assert (await client.delete(f"{URL}/{key}")).status_code == 204
    db_session.expire_all()
    body = (await client.get(URL)).json()
    switch = _switch(body, key)
    assert switch["enabled"] is False
    assert switch["source"] in {"env", "default"}

    logs = (await db_session.scalars(select(AuditLog).order_by(AuditLog.created_at))).all()
    assert len(logs) == 2
    assert logs[1].action == "feature_switch.reset"
    assert logs[1].detail["old"] is True and logs[1].detail["new"] is False


async def test_both_new_switches_appear_in_the_overview(api) -> None:
    client, _ = api
    body = (await client.get(URL)).json()
    names = {row["family"] for row in body["families"]}
    assert {"jdbc", "qradar_source_pause"} <= names
    for key in NEW_KEYS:
        assert _switch(body, key)["enabled"] is False


async def test_policy_off_preserves_existing_behavior(api) -> None:
    """The real Features entry with the new switches off: every older row is unchanged."""
    client, _ = api
    body = (await client.get(URL)).json()
    assert body["reason"] is None
    families = {row["family"]: row for row in body["families"]}
    for name in ("waf", "ips", "geo", "inventory", "volume"):
        assert name in families
    assert "waf_collection_enabled" in families["waf"]["switches"]
    assert _switch(body, "waf_collection_enabled")["enabled"] is False
    assert all(_switch(body, key)["enabled"] is False for key in NEW_KEYS)


def _sync_url() -> str:
    url = os.environ.get("TEST_DATABASE_URL")
    if not url:
        pytest.skip("TEST_DATABASE_URL not set")
    return url.replace("+asyncpg", "+psycopg")


def test_0074_round_trip_allows_both_keys_and_has_no_drift() -> None:
    from alembic.config import Config
    from alembic.util.exc import AutogenerateDiffsDetected
    from sqlalchemy.exc import IntegrityError

    from alembic import command
    from tests.integration.schema_reset import reset_public_schema

    url = _sync_url()
    reset_public_schema(url)
    cfg = Config()
    cfg.set_main_option("script_location", "alembic")
    cfg.set_main_option("sqlalchemy.url", url)
    engine = create_engine(url, future=True)
    insert = (
        "INSERT INTO feature_switch (key, enabled, updated_at, updated_by) "
        "VALUES ('{}', true, now(), 'alice')"
    )
    try:
        command.upgrade(cfg, "0073")
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(insert.format("jdbc_collection_enabled")))

        command.upgrade(cfg, "0074")
        with engine.begin() as conn:
            for key in NEW_KEYS:
                conn.execute(text(insert.format(key)))
            count = conn.execute(text("SELECT count(*) FROM feature_switch")).scalar()
        assert count == 2

        command.downgrade(cfg, "0073")
        with engine.begin() as conn:
            count = conn.execute(text("SELECT count(*) FROM feature_switch")).scalar()
            assert count == 0
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(insert.format("qradar_source_pause_enabled")))

        command.upgrade(cfg, "head")
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()


