"""Migration 0022: the geo_country_bucket hypertable, round trip and no drift."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")
COLUMNS = {
    "instance_id": ("uuid", "NO"),
    "bucket_start": ("timestamp with time zone", "NO"),
    "direction": ("character varying", "NO"),
    "slot": ("character varying", "NO"),
    "bucket_seconds": ("integer", "NO"),
    "country_code": ("character", "YES"),
    "remainder_kind": ("character varying", "YES"),
    "events": ("bigint", "NO"),
    "measurement": ("character varying", "NO"),
    "query_version": ("character varying", "NO"),
    "collected_at": ("timestamp with time zone", "NO"),
}


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    engine = create_engine(sync_url, future=True)
    with engine.begin() as connection:
        connection.execute(text("DROP SCHEMA public CASCADE"))
        connection.execute(text("CREATE SCHEMA public"))
    engine.dispose()
    return sync_url


def _exists(connection, table: str) -> bool:  # type: ignore[no-untyped-def]
    return bool(
        connection.execute(
            text("SELECT to_regclass(:table)").bindparams(table=f"public.{table}")
        ).scalar()
    )


def _insert(connection, instance, **over) -> None:  # type: ignore[no-untyped-def]
    values = {
        "i": instance,
        "b": "2026-10-13 12:00:00+00",
        "d": "SOURCE",
        "c": "US",
        "r": None,
        "e": 5,
        "m": "EXACT",
        "s": 300,
        **over,
    }
    connection.execute(
        text(
            "INSERT INTO geo_country_bucket (instance_id, bucket_start, bucket_seconds, "
            "direction, country_code, remainder_kind, events, measurement, query_version, "
            "collected_at) VALUES (:i, :b, :s, :d, :c, :r, :e, :m, 'geo-country-v1', now())"
        ),
        values,
    )


def _rejected(engine, instance, **over) -> bool:  # type: ignore[no-untyped-def]
    try:
        with engine.begin() as connection:
            _insert(connection, instance, **over)
    except IntegrityError:
        return True
    return False


def test_0022_round_trip_constraints_uniqueness_and_no_drift(clean_db: str) -> None:
    from alembic.script import ScriptDirectory
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    assert ScriptDirectory.from_config(config).get_revision("0022").down_revision == "0021"
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "0022")
        with engine.begin() as connection:
            columns = {
                row.column_name: (row.data_type, row.is_nullable)
                for row in connection.execute(
                    text(
                        "SELECT column_name, data_type, is_nullable FROM "
                        "information_schema.columns WHERE table_name = 'geo_country_bucket'"
                    )
                )
            }
            assert columns == COLUMNS
            assert connection.execute(
                text(
                    "SELECT character_maximum_length FROM information_schema.columns "
                    "WHERE table_name = 'geo_country_bucket' AND column_name = 'country_code'"
                )
            ).scalar_one() == 2

            seeded = connection.execute(
                text("SELECT cadence_seconds FROM search_cadence WHERE family = 'GEO_COLLECTION'")
            ).scalar_one()
            assert seeded == 3600
            assert connection.execute(
                text(
                    "SELECT count(*) FROM timescaledb_information.hypertables "
                    "WHERE hypertable_name = 'geo_country_bucket'"
                )
            ).scalar_one() == 1
            pk = connection.execute(
                text(
                    "SELECT array_agg(att.attname ORDER BY ordinality) FROM pg_constraint con "
                    "JOIN unnest(con.conkey) WITH ORDINALITY AS key(attnum, ordinality) ON true "
                    "JOIN pg_attribute att ON att.attrelid = con.conrelid "
                    "AND att.attnum = key.attnum "
                    "WHERE con.conrelid = 'geo_country_bucket'::regclass AND con.contype = 'p' "
                    "GROUP BY con.oid"
                )
            ).scalar_one()
            assert pk == ["instance_id", "bucket_start", "direction", "slot"]
            instance = connection.execute(
                text(
                    "INSERT INTO qradar_instance (id, name, console_host, api_version, "
                    "verify_ssl, provider_kind, mcp_enabled, enabled, status, "
                    "consecutive_failures) VALUES (gen_random_uuid(), 'lab', 'q.lab.local', "
                    "'20.0', true, 'REST', false, true, 'HEALTHY', 0) RETURNING id"
                )
            ).scalar_one()

        # A country row and a remainder row.
        with engine.begin() as connection:
            _insert(connection, instance)
            _insert(connection, instance, c=None, r="UNRESOLVED", e=9)
            slots = {
                row[0]
                for row in connection.execute(text("SELECT slot FROM geo_country_bucket"))
            }
            assert slots == {"US", "UNRESOLVED"}

        # Uniqueness: one row per (instance, bucket, direction, code-or-remainder).
        assert _rejected(engine, instance)
        assert _rejected(engine, instance, c=None, r="UNRESOLVED")
        with engine.begin() as connection:
            _insert(connection, instance, d="DESTINATION")
            _insert(connection, instance, c="DE")
            _insert(connection, instance, c=None, r="OVER_CAP")
            _insert(connection, instance, b="2026-10-13 12:05:00+00")

        # The CHECKs.
        assert _rejected(engine, instance, c="DE", r="UNRESOLVED", b="2026-10-13 13:00:00+00")
        assert _rejected(engine, instance, c=None, r=None, b="2026-10-13 13:00:00+00")
        assert _rejected(engine, instance, c="U1", b="2026-10-13 13:00:00+00")
        assert _rejected(engine, instance, c="us", b="2026-10-13 13:00:00+00")
        assert _rejected(engine, instance, c=None, r="NO_ADDRESS", b="2026-10-13 13:00:00+00")
        assert _rejected(engine, instance, d="BOTH", b="2026-10-13 13:00:00+00")
        assert _rejected(engine, instance, m="GUESS", b="2026-10-13 13:00:00+00")
        assert _rejected(engine, instance, e=-1, b="2026-10-13 13:00:00+00")
        assert _rejected(engine, instance, s=0, b="2026-10-13 13:00:00+00")
        assert not _rejected(engine, instance, m="LOWER_BOUND", b="2026-10-13 13:00:00+00")

        # The foreign key cascades.
        with engine.begin() as connection:
            connection.execute(text("DELETE FROM qradar_instance WHERE id = :i"), {"i": instance})
            assert connection.execute(
                text("SELECT count(*) FROM geo_country_bucket")
            ).scalar_one() == 0

        command.downgrade(config, "0021")
        with engine.connect() as connection:
            assert not _exists(connection, "geo_country_bucket")
            assert _exists(connection, "catchall_bucket")
            assert not connection.execute(
                text("SELECT 1 FROM search_cadence WHERE family = 'GEO_COLLECTION'")
            ).first()

        command.upgrade(config, "head")
        with engine.connect() as connection:
            assert _exists(connection, "geo_country_bucket")
            assert connection.execute(
                text("SELECT count(*) FROM search_cadence WHERE family = 'GEO_COLLECTION'")
            ).scalar_one() == 1
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
