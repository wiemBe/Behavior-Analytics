"""Migration 0049: how a geography bucket was collected (GEO-6). Round trip, no guess, no drift."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

from tests.integration.schema_reset import reset_public_schema

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")
INSTANCE = "66666666-6666-6666-6666-666666666666"
ROW = (
    "INSERT INTO geo_country_bucket (instance_id, bucket_start, direction, bucket_seconds, "
    "country_code, events, measurement, query_version, collected_at {extra}) "
    "VALUES (CAST(:i AS uuid), now(), 'SOURCE', 300, 'US', 1, 'EXACT', 'v', now() {values})"
)


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def _columns(engine) -> dict[str, tuple[str, str, str | None]]:  # type: ignore[no-untyped-def]
    with engine.connect() as conn:
        return {
            row.column_name: (row.data_type, row.is_nullable, row.column_default)
            for row in conn.execute(
                text(
                    "SELECT column_name, data_type, is_nullable, column_default "
                    "FROM information_schema.columns "
                    "WHERE table_schema = 'public' AND table_name = 'geo_country_bucket'"
                )
            )
        }


def test_0049_adds_two_nullable_columns_and_leaves_existing_rows_unknown(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = _alembic_config(clean_db)
    command.upgrade(cfg, "0048")
    engine = create_engine(clean_db, future=True)
    try:
        assert "country_source" not in _columns(engine)
        with engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO qradar_instance (id, name, console_host, api_version, "
                    " verify_ssl, provider_kind, mcp_enabled, enabled, status, "
                    " consecutive_failures) "
                    "VALUES (CAST(:i AS uuid), 'lab', 'qradar.lab.local', '20.0', true, "
                    " 'REST', false, true, 'HEALTHY', 0)"
                ).bindparams(i=INSTANCE)
            )
            conn.execute(text(ROW.format(extra="", values="")).bindparams(i=INSTANCE))

        command.upgrade(cfg, "0049")

        columns = _columns(engine)
        assert columns["country_source"] == ("character varying", "YES", None)
        assert columns["country_property"] == ("character varying", "YES", None)
        with engine.connect() as conn:
            # An existing row is unknown: not backfilled with a guess.
            assert conn.execute(
                text("SELECT country_source, country_property FROM geo_country_bucket")
            ).one() == (None, None)

        with engine.begin() as conn:
            conn.execute(
                text("UPDATE geo_country_bucket SET country_source = 'LOOKUP'")
            )
            conn.execute(
                text("UPDATE geo_country_bucket SET country_source = 'PROPERTY', "
                     "country_property = 'Source Geographic Location'")
            )
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text("UPDATE geo_country_bucket SET country_source = 'GUESS'"))

        command.downgrade(cfg, "0048")
        columns = _columns(engine)
        assert "country_source" not in columns and "country_property" not in columns
        with engine.connect() as conn:
            assert conn.execute(text("SELECT count(*) FROM geo_country_bucket")).scalar() == 1

        command.upgrade(cfg, "head")
        assert "country_source" in _columns(engine)
        with engine.connect() as conn:
            assert conn.execute(
                text("SELECT country_source FROM geo_country_bucket")
            ).scalar() is None
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
