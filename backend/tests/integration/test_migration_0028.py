"""Migration 0028: only untouched one-hour defaults move, with append-only audit."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text

from tests.integration.schema_reset import reset_public_schema

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def _cadences(connection) -> dict[str, tuple[int, str | None]]:  # type: ignore[no-untyped-def]
    rows = connection.execute(
        text("SELECT family, cadence_seconds, updated_by FROM search_cadence ORDER BY family")
    )
    return {row.family: (row.cadence_seconds, row.updated_by) for row in rows}


def _migration_audits(connection) -> list[tuple[str, dict]]:  # type: ignore[no-untyped-def]
    rows = connection.execute(
        text(
            "SELECT object_id, detail FROM audit_log "
            "WHERE actor = 'system:migration-0028' ORDER BY created_at, object_id"
        )
    )
    return [(row.object_id, row.detail) for row in rows]


def test_0028_moves_only_untouched_defaults_and_audits_each_direction(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "0027")
        with engine.begin() as connection:
            connection.execute(
                text(
                    "UPDATE search_cadence SET updated_by = 'operator' "
                    "WHERE family = 'PHASE_A_VOLUME'"
                )
            )
            connection.execute(
                text(
                    "UPDATE search_cadence SET cadence_seconds = 7200, updated_by = 'operator' "
                    "WHERE family = 'WAF_COLLECTION'"
                )
            )

        command.upgrade(config, "0028")
        with engine.connect() as connection:
            rows = _cadences(connection)
            assert rows["PHASE_A_VOLUME"] == (3600, "operator")
            assert rows["WAF_COLLECTION"] == (7200, "operator")
            five = {family for family, value in rows.items() if value == (300, None)}
            assert five == {
                "ANOMALY_EXPLANATION",
                "CATCHALL_SENDERS",
                "GEO_COLLECTION",
                "PROPERTY_WATCH",
                "RULE_MATCH",
            }
            assert rows["IPS_COLLECTION"] == (900, None)
            moved = five | {"IPS_COLLECTION"}
            audits = _migration_audits(connection)
            assert {family for family, _detail in audits} == moved
            for family, detail in audits:
                new = 900 if family == "IPS_COLLECTION" else 300
                assert detail == {"old": 3600, "new": new, "reason": "D-28 default"}

        command.downgrade(config, "0027")
        with engine.connect() as connection:
            rows = _cadences(connection)
            assert rows["PHASE_A_VOLUME"] == (3600, "operator")
            assert rows["WAF_COLLECTION"] == (7200, "operator")
            assert all(rows[family] == (3600, None) for family in moved)
            audits = _migration_audits(connection)
            assert len(audits) == 12
            downgrade = audits[6:]
            assert {family for family, _detail in downgrade} == moved
            for family, detail in downgrade:
                old = 900 if family == "IPS_COLLECTION" else 300
                assert detail == {"old": old, "new": 3600, "reason": "downgrade of 0028"}

        command.upgrade(config, "head")
        with engine.connect() as connection:
            rows = _cadences(connection)
            assert rows["PHASE_A_VOLUME"] == (3600, "operator")
            assert rows["WAF_COLLECTION"] == (7200, "operator")
            assert all(rows[family] == (300, None) for family in five)
            assert rows["IPS_COLLECTION"] == (900, None)
            assert len(_migration_audits(connection)) == 18
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()


def test_fresh_install_has_all_eight_families_at_their_default(clean_db: str) -> None:
    from alembic import command

    config = _alembic_config(clean_db)
    command.upgrade(config, "head")
    engine = create_engine(clean_db, future=True)
    try:
        with engine.connect() as connection:
            rows = _cadences(connection)
            assert len(rows) == 8
            assert set(rows) == {
                "PHASE_A_VOLUME",
                "WAF_COLLECTION",
                "ANOMALY_EXPLANATION",
                "RULE_MATCH",
                "IPS_COLLECTION",
                "PROPERTY_WATCH",
                "CATCHALL_SENDERS",
                "GEO_COLLECTION",
            }
            for family, value in rows.items():
                expected = 900 if family in {"WAF_COLLECTION", "IPS_COLLECTION"} else 300
                assert value == (expected, None)
            audits = _migration_audits(connection)
            assert len(audits) == 8
            assert {family for family, _detail in audits} == set(rows)
    finally:
        engine.dispose()
