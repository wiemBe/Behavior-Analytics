"""Migration 0024: custom rules, a data-carrying round trip, and no drift.

Downgrade drops the three new tables, and the rows in them, by design. Phase A
data is what the round trip has to carry: a log source inserted beside the
rules is still there after downgrade and the following upgrade. `alembic check`
is the authority for model drift.
"""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

from tests.integration.schema_reset import reset_public_schema

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")
INSTANCE = "11111111-1111-1111-1111-111111111111"
KEPT = "22222222-2222-2222-2222-222222222221"
DROPPED = "22222222-2222-2222-2222-222222222222"
LOG_RULE = "33333333-3333-3333-3333-333333333331"
FLEET_RULE = "33333333-3333-3333-3333-333333333332"
OPEN_BREACH = "44444444-4444-4444-4444-444444444441"
RESOLVED_BREACH = "44444444-4444-4444-4444-444444444442"
FLEET_BREACH = "44444444-4444-4444-4444-444444444443"


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def _exists(connection, table: str) -> bool:  # type: ignore[no-untyped-def]
    return bool(
        connection.execute(
            text("SELECT to_regclass(:table)").bindparams(table=f"public.{table}")
        ).scalar()
    )


def _rejects(engine, sql: str, params: dict[str, object], match: str) -> None:  # type: ignore[no-untyped-def]
    with pytest.raises(IntegrityError, match=match), engine.begin() as connection:
        connection.execute(text(sql), params)


def test_0024_round_trip_carries_phase_a_data_and_has_no_drift(clean_db: str) -> None:
    from alembic.runtime.migration import MigrationContext
    from alembic.script import ScriptDirectory
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    script = ScriptDirectory.from_config(config)
    revision = script.get_revision("0024")
    assert revision is not None
    assert revision.down_revision == "0023"
    assert script.get_current_head() == "0024"

    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "head")
        with engine.connect() as connection:
            context = MigrationContext.configure(connection)
            assert context.get_current_revision() == "0024"

        with engine.begin() as connection:
            connection.execute(
                text(
                    "INSERT INTO qradar_instance (id, name, console_host, api_version, "
                    " verify_ssl, provider_kind, mcp_enabled, enabled, status, "
                    " consecutive_failures) "
                    "VALUES (CAST(:i AS uuid), 'lab', 'qradar.lab.local', '20.0', true, "
                    " 'REST', false, true, 'HEALTHY', 0)"
                ),
                {"i": INSTANCE},
            )
            for source_id, qradar_id, name in (
                (KEPT, 11, "kept-source"),
                (DROPPED, 12, "edge-fw"),
            ):
                connection.execute(
                    text(
                        "INSERT INTO log_source (id, instance_id, qradar_id, name, enabled, "
                        " criticality, monitoring_enabled, maintenance_mode, "
                        " business_hours_only, business_hours_start, business_hours_end, "
                        " business_days, timezone_name, custom_thresholds, first_seen_at) "
                        "VALUES (CAST(:id AS uuid), CAST(:i AS uuid), :qid, :name, true, "
                        " 'MEDIUM', true, false, false, 8, 18, "
                        " CAST('[1,2,3,4,5]' AS jsonb), 'UTC', CAST('{}' AS jsonb), now())"
                    ),
                    {"id": source_id, "i": INSTANCE, "qid": qradar_id, "name": name},
                )
            connection.execute(
                text(
                    "INSERT INTO custom_rule (name, subject_kind, log_source_id, metric, "
                    " operator, threshold_value, sustain_buckets, recovery_buckets, severity, "
                    " enabled, consecutive_breaching, consecutive_under, id) "
                    "VALUES ('sustained-volume', 'LOG_SOURCE', CAST(:ls AS uuid), "
                    " 'event_count', 'GT', 100, 3, 2, 'HIGH', true, 0, 0, CAST(:id AS uuid))"
                ),
                {"ls": DROPPED, "id": LOG_RULE},
            )
            connection.execute(
                text(
                    "INSERT INTO custom_rule (name, subject_kind, source_class, metric, "
                    " operator, threshold_value, sustain_buckets, recovery_buckets, severity, "
                    " enabled, consecutive_breaching, consecutive_under, id) "
                    "VALUES ('linux-eps', 'FLEET_CLASS', 'LINUX', 'eps', 'GT', 0.5, 1, 1, "
                    " 'MEDIUM', true, 0, 0, CAST(:id AS uuid))"
                ),
                {"id": FLEET_RULE},
            )
            connection.execute(
                text(
                    "INSERT INTO custom_rule_breach (rule_id, state, first_bucket_start, "
                    " last_bucket_start, opened_at, worst_value, worst_measurement, "
                    " last_value, last_measurement, unmeasured_buckets, subject_label, "
                    " details, id) "
                    "VALUES (CAST(:rule AS uuid), 'OPEN', '2026-07-15 10:10+00', "
                    " '2026-07-15 10:10+00', '2026-07-15 10:16+00', 400, 'EXACT', 400, "
                    " 'EXACT', 0, 'edge-fw', "
                    " CAST('{\"metric\": \"event_count\", \"subject_label\": \"edge-fw\"}' "
                    " AS jsonb), CAST(:id AS uuid))"
                ),
                {"rule": LOG_RULE, "id": OPEN_BREACH},
            )
            connection.execute(
                text(
                    "INSERT INTO custom_rule_breach (rule_id, state, first_bucket_start, "
                    " last_bucket_start, opened_at, resolved_at, worst_value, "
                    " worst_measurement, last_value, last_measurement, unmeasured_buckets, "
                    " subject_label, details, id) "
                    "VALUES (CAST(:rule AS uuid), 'RESOLVED', '2026-07-15 09:00+00', "
                    " '2026-07-15 09:10+00', '2026-07-15 09:16+00', '2026-07-15 09:30+00', "
                    " 20, 'EXACT', 1, 'EXACT', 0, 'edge-fw', CAST('{}' AS jsonb), "
                    " CAST(:id AS uuid))"
                ),
                {"rule": LOG_RULE, "id": RESOLVED_BREACH},
            )
            connection.execute(
                text(
                    "INSERT INTO custom_rule_breach (rule_id, state, first_bucket_start, "
                    " last_bucket_start, opened_at, resolved_at, unmeasured_buckets, "
                    " subject_label, details, id) "
                    "VALUES (CAST(:rule AS uuid), 'RESOLVED', '2026-07-15 08:00+00', "
                    " '2026-07-15 08:05+00', '2026-07-15 08:10+00', '2026-07-15 08:20+00', "
                    " 0, 'LINUX', CAST('{}' AS jsonb), CAST(:id AS uuid))"
                ),
                {"rule": FLEET_RULE, "id": FLEET_BREACH},
            )
            connection.execute(
                text(
                    "INSERT INTO custom_rule_watermark (subject_kind, evaluated_through, "
                    " updated_at) VALUES ('LOG_SOURCE', '2026-07-15 09:55+00', now())"
                )
            )
            connection.execute(
                text(
                    "UPDATE custom_rule SET active_breach_id = CAST(:b AS uuid) "
                    "WHERE id = CAST(:id AS uuid)"
                ),
                {"b": OPEN_BREACH, "id": LOG_RULE},
            )

        with engine.connect() as connection:
            rule = connection.execute(
                text(
                    "SELECT name, metric, threshold_value, sustain_buckets, active_breach_id "
                    "FROM custom_rule WHERE id = CAST(:id AS uuid)"
                ),
                {"id": LOG_RULE},
            ).one()
            assert rule.name == "sustained-volume"
            assert rule.metric == "event_count"
            assert rule.threshold_value == 100
            assert rule.sustain_buckets == 3
            assert str(rule.active_breach_id) == OPEN_BREACH
            breach = connection.execute(
                text(
                    "SELECT state, subject_label, details, worst_measurement, worst_value "
                    "FROM custom_rule_breach WHERE id = CAST(:id AS uuid)"
                ),
                {"id": OPEN_BREACH},
            ).one()
            assert breach.state == "OPEN"
            assert breach.subject_label == "edge-fw"
            assert breach.details["metric"] == "event_count"
            assert breach.details["subject_label"] == "edge-fw"
            assert breach.worst_measurement == "EXACT"
            assert breach.worst_value == 400
            watermark = connection.execute(
                text(
                    "SELECT evaluated_through FROM custom_rule_watermark "
                    "WHERE subject_kind = 'LOG_SOURCE'"
                )
            ).scalar_one()
            assert watermark.isoformat().startswith("2026-07-15T09:55:00")
            indexdef = connection.execute(
                text(
                    "SELECT indexdef FROM pg_indexes "
                    "WHERE indexname = 'uq_custom_rule_breach_active'"
                )
            ).scalar_one()
            assert "UNIQUE" in indexdef
            assert "RESOLVED" in indexdef

        _rule_sql = (
            "INSERT INTO custom_rule (name, subject_kind, log_source_id, source_class, "
            " metric, operator, threshold_value, sustain_buckets, recovery_buckets, "
            " severity, enabled, consecutive_breaching, consecutive_under, id) "
            "VALUES (:name, :kind, CAST(:ls AS uuid), :cls, 'event_count', :op, :threshold, "
            " :sustain, :recovery, :severity, true, 0, 0, gen_random_uuid())"
        )
        base = {
            "name": "reject-me",
            "kind": "LOG_SOURCE",
            "ls": KEPT,
            "cls": None,
            "op": "GT",
            "threshold": 1,
            "sustain": 1,
            "recovery": 1,
            "severity": "LOW",
        }
        _rejects(
            engine,
            _rule_sql,
            {**base, "name": "sustained-volume"},
            "uq_custom_rule_name",
        )
        _rejects(engine, _rule_sql, {**base, "name": ""}, "ck_custom_rule_name_not_empty")
        _rejects(engine, _rule_sql, {**base, "op": "NE"}, "ck_custom_rule_operator_known")
        _rejects(
            engine, _rule_sql, {**base, "severity": "HUGE"}, "ck_custom_rule_severity_known"
        )
        _rejects(
            engine,
            _rule_sql,
            {**base, "threshold": -1},
            "ck_custom_rule_threshold_non_negative",
        )
        _rejects(
            engine, _rule_sql, {**base, "sustain": 0}, "ck_custom_rule_sustain_buckets_positive"
        )
        _rejects(
            engine,
            _rule_sql,
            {**base, "recovery": 0},
            "ck_custom_rule_recovery_buckets_positive",
        )
        _rejects(
            engine,
            _rule_sql,
            {**base, "ls": None},
            "ck_custom_rule_subject_matches_kind",
        )
        _rejects(
            engine,
            _rule_sql,
            {**base, "name": "extra-class", "cls": "LINUX"},
            "ck_custom_rule_subject_matches_kind",
        )
        _rejects(
            engine,
            _rule_sql,
            {**base, "name": "fleet-missing", "kind": "FLEET_CLASS", "ls": None, "cls": None},
            "ck_custom_rule_subject_matches_kind",
        )

        _breach_sql = (
            "INSERT INTO custom_rule_breach (rule_id, state, first_bucket_start, "
            " last_bucket_start, opened_at, worst_measurement, unmeasured_buckets, "
            " subject_label, details, id) "
            "VALUES (CAST(:rule AS uuid), :state, '2026-07-15 11:00+00', "
            " '2026-07-15 11:00+00', '2026-07-15 11:05+00', :measurement, :unmeasured, "
            " 'edge-fw', CAST('{}' AS jsonb), gen_random_uuid())"
        )
        _rejects(
            engine,
            _breach_sql,
            {"rule": FLEET_RULE, "state": "CANDIDATE", "measurement": "EXACT", "unmeasured": 0},
            "ck_custom_rule_breach_state_known",
        )
        _rejects(
            engine,
            _breach_sql,
            {"rule": FLEET_RULE, "state": "RESOLVED", "measurement": "PARTIAL", "unmeasured": 0},
            "ck_custom_rule_breach_worst_measurement_known",
        )
        _rejects(
            engine,
            _breach_sql,
            {"rule": FLEET_RULE, "state": "RESOLVED", "measurement": "EXACT", "unmeasured": -1},
            "ck_custom_rule_breach_unmeasured_buckets_non_negative",
        )
        _rejects(
            engine,
            _breach_sql,
            {"rule": LOG_RULE, "state": "OPEN", "measurement": "EXACT", "unmeasured": 0},
            "uq_custom_rule_breach_active",
        )

        with engine.begin() as connection:
            connection.execute(
                text("DELETE FROM log_source WHERE id = CAST(:id AS uuid)"), {"id": DROPPED}
            )
            assert (
                connection.execute(
                    text("SELECT count(*) FROM custom_rule WHERE id = CAST(:id AS uuid)"),
                    {"id": LOG_RULE},
                ).scalar_one()
                == 0
            )
            assert (
                connection.execute(
                    text(
                        "SELECT count(*) FROM custom_rule_breach WHERE rule_id = CAST(:id AS uuid)"
                    ),
                    {"id": LOG_RULE},
                ).scalar_one()
                == 0
            )
            assert (
                connection.execute(text("SELECT count(*) FROM custom_rule")).scalar_one() == 1
            )
            connection.execute(
                text("DELETE FROM custom_rule WHERE id = CAST(:id AS uuid)"), {"id": FLEET_RULE}
            )
            assert (
                connection.execute(
                    text("SELECT count(*) FROM custom_rule_breach")
                ).scalar_one()
                == 0
            )
            assert connection.execute(text("SELECT count(*) FROM log_source")).scalar_one() == 1

        command.downgrade(config, "0023")
        with engine.connect() as connection:
            assert not _exists(connection, "custom_rule")
            assert not _exists(connection, "custom_rule_breach")
            assert not _exists(connection, "custom_rule_watermark")
            assert connection.execute(text("SELECT name FROM log_source")).scalar_one() == (
                "kept-source"
            )
            context = MigrationContext.configure(connection)
            assert context.get_current_revision() == "0023"

        command.upgrade(config, "head")
        with engine.connect() as connection:
            assert _exists(connection, "custom_rule")
            assert connection.execute(text("SELECT count(*) FROM custom_rule")).scalar_one() == 0
            assert (
                connection.execute(text("SELECT count(*) FROM custom_rule_breach")).scalar_one()
                == 0
            )
            assert connection.execute(text("SELECT name FROM log_source")).scalar_one() == (
                "kept-source"
            )
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
