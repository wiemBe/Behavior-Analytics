"""Migration 0060: the rule-incident tables, the `rule` family and its e-mail type.

Runs the real revision up, down and up again without ``alembic.ini`` so the
process-wide logging configuration is untouched (AGENTS.md §4), pins the five
widened CHECKs in both directions, and refuses a downgrade that would lose a
`rule` record or an administrator's ``analytics_rule`` template. DB-gated.
"""

from __future__ import annotations

from datetime import UTC, datetime

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.models.instance import QRadarInstance
from app.models.rule import AnalyticsRule
from app.models.rule_anomaly import (
    RuleAnomaly,
    RuleAnomalyTransition,
    RuleDetectorState,
)
from tests.integration.schema_reset import reset_public_schema
from tests.integration.test_migrations import _alembic_config, _sync_url, _table_exists

pytestmark = pytest.mark.integration

_NEW_TABLES = ("rule_anomaly", "rule_anomaly_transition", "rule_detector_state")

_TRIAGE = (
    "INSERT INTO anomaly_triage (id, family, anomaly_id, status, updated_by, version) "
    "VALUES (gen_random_uuid(), '{family}', gen_random_uuid(), 'NEW', 'seed', 1)"
)
_POLICY = (
    "INSERT INTO alert_policy (id, scope_kind, scope_value, family, detector_type, mode) "
    "VALUES (gen_random_uuid(), '{scope}', '{value}', '{family}', NULL, 'ALERT')"
)
_SUPPRESSION = (
    "INSERT INTO alert_suppression (id, family, subject_id, detector_type, kind, reason, "
    "owner, starts_at, ends_at, reference, created_by) VALUES "
    "(gen_random_uuid(), '{family}', gen_random_uuid(), NULL, 'ANALYST', 'note', "
    "'analyst', '2026-11-01 00:00+00', '2026-11-08 00:00+00', NULL, 'analyst')"
)
_TEMPLATE = (
    "INSERT INTO email_template (id, alert_type, subject, html_body, enabled) "
    "VALUES (gen_random_uuid(), '{kind}', 's', '<p>x</p>', true)"
)


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def _downgrade(cfg) -> None:  # type: ignore[no-untyped-def]
    from alembic import command

    command.downgrade(cfg, "0059")


def _version(engine) -> str:  # type: ignore[no-untyped-def]
    with engine.connect() as conn:
        return str(conn.execute(text("SELECT version_num FROM alembic_version")).scalar_one())


def _seed_blocker(engine, family: str) -> None:
    """One row that the 0060 downgrade must refuse to strand."""
    if family == "triage":
        with engine.begin() as conn:
            conn.execute(text(_TRIAGE.format(family="rule")))
    elif family == "policy":
        with engine.begin() as conn:
            conn.execute(text(_POLICY.format(scope="SOURCE", value="r", family="rule")))
    elif family == "suppression":
        with engine.begin() as conn:
            conn.execute(text(_SUPPRESSION.format(family="rule")))
    elif family == "suppression_hit":
        with engine.begin() as conn:
            conn.execute(text(_SUPPRESSION.format(family="log_source")))
            conn.execute(
                text(
                    "INSERT INTO alert_suppression_hit (id, suppression_id, family, "
                    "anomaly_id, detector_type, bucket_start, occurred_at) "
                    "SELECT gen_random_uuid(), id, 'rule', gen_random_uuid(), "
                    "'RULE_STORM', '2026-11-02 00:00+00', '2026-11-02 00:01+00' "
                    "FROM alert_suppression"
                )
            )
    else:
        with engine.begin() as conn:
            conn.execute(text(_TEMPLATE.format(kind="analytics_rule")))


def _clear_blockers(engine) -> None:
    with engine.begin() as conn:
        conn.execute(text("DELETE FROM anomaly_triage WHERE family = 'rule'"))
        conn.execute(text("DELETE FROM alert_policy WHERE family = 'rule'"))
        conn.execute(text("DELETE FROM alert_suppression_hit WHERE family = 'rule'"))
        conn.execute(text("DELETE FROM alert_suppression WHERE family = 'rule'"))
        conn.execute(text("DELETE FROM email_template WHERE alert_type = 'analytics_rule'"))


def test_0060_round_trip_widens_the_checks_and_leaves_no_drift(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(cfg, "0059")
        for table in _NEW_TABLES:
            assert not _table_exists(engine, table), table

        command.upgrade(cfg, "0060")
        for table in _NEW_TABLES:
            assert _table_exists(engine, table), table

        # Every widened CHECK accepts the new family, and still refuses a made-up one.
        with engine.begin() as conn:
            conn.execute(text(_TRIAGE.format(family="rule")))
            conn.execute(text(_POLICY.format(scope="SOURCE", value="r", family="rule")))
            conn.execute(text(_SUPPRESSION.format(family="rule")))
            conn.execute(text(_SUPPRESSION.format(family="log_source")))
            conn.execute(
                text(
                    "INSERT INTO alert_suppression_hit (id, suppression_id, family, "
                    "anomaly_id, detector_type, bucket_start, occurred_at) "
                    "SELECT gen_random_uuid(), id, 'rule', gen_random_uuid(), "
                    "'RULE_SILENCE', '2026-11-02 00:00+00', '2026-11-02 00:01+00' "
                    "FROM alert_suppression WHERE family = 'log_source'"
                )
            )
            conn.execute(text(_TEMPLATE.format(kind="analytics_rule")))
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(_TRIAGE.format(family="not_a_family")))
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(
                text(_POLICY.format(scope="SOURCE", value="x", family="not_a_family"))
            )
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(_SUPPRESSION.format(family="not_a_family")))
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO alert_suppression_hit (id, suppression_id, family, "
                    "anomaly_id, detector_type, bucket_start, occurred_at) "
                    "SELECT gen_random_uuid(), id, 'not_a_family', gen_random_uuid(), "
                    "'RULE_SILENCE', '2026-11-02 00:00+00', '2026-11-02 00:01+00' "
                    "FROM alert_suppression WHERE family = 'log_source'"
                )
            )
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(_TEMPLATE.format(kind="not_a_type")))

        # No drift check here: `alembic check` compares against head, so it only runs
        # after the upgrade to head below (the project rule, test_migrations.py).
        _clear_blockers(engine)
        _downgrade(cfg)
        for table in _NEW_TABLES:
            assert not _table_exists(engine, table), table
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(_TRIAGE.format(family="rule")))
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(_TEMPLATE.format(kind="analytics_rule")))

        command.upgrade(cfg, "head")
        for table in _NEW_TABLES:
            assert _table_exists(engine, table), table
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected after the round trip:\n{exc}")
    finally:
        engine.dispose()


def test_0060_cascade_and_detector_state_uniqueness(clean_db: str) -> None:
    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(cfg, "head")
        with Session(engine) as session:
            instance = QRadarInstance(
                name="lab",
                console_host="lab.local",
                api_version="20.0",
                provider_kind="REST",
                mcp_enabled=False,
                enabled=True,
            )
            session.add(instance)
            session.flush()
            rule = AnalyticsRule(
                instance_id=instance.id,
                qradar_id=101,
                name="rule-101",
                enabled=True,
                is_building_block=False,
            )
            session.add(rule)
            session.flush()
            detected = datetime(2026, 11, 1, tzinfo=UTC)
            anomaly = RuleAnomaly(
                rule_id=rule.id,
                qradar_id=rule.qradar_id,
                is_building_block=False,
                detector_type="RULE_SILENCE",
                fingerprint="fp-1",
                severity="MEDIUM",
                state="OPEN",
                detected_at=detected,
                details={},
            )
            session.add(anomaly)
            session.flush()
            session.add(
                RuleAnomalyTransition(
                    rule_anomaly_id=anomaly.id,
                    to_state="OPEN",
                    occurred_at=detected,
                )
            )
            session.add(
                RuleDetectorState(
                    rule_id=rule.id,
                    detector_type="RULE_SILENCE",
                    state="OPEN",
                    open_anomaly_id=anomaly.id,
                )
            )
            session.commit()
            rule_id = rule.id
            anomaly_id = anomaly.id

        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO rule_detector_state (id, rule_id, detector_type, "
                    "consecutive_anomalous, consecutive_healthy, state) VALUES "
                    "(gen_random_uuid(), :rule_id, 'RULE_SILENCE', 0, 0, 'NORMAL')"
                ).bindparams(rule_id=rule_id)
            )

        with engine.begin() as conn:
            conn.execute(
                text("DELETE FROM analytics_rule WHERE id = :rule_id").bindparams(
                    rule_id=rule_id
                )
            )
        with engine.connect() as conn:
            assert (
                conn.execute(
                    text("SELECT count(*) FROM rule_anomaly WHERE id = :value").bindparams(
                        value=anomaly_id
                    )
                ).scalar_one()
                == 0
            )
            assert (
                conn.execute(
                    text(
                        "SELECT count(*) FROM rule_anomaly_transition "
                        "WHERE rule_anomaly_id = :value"
                    ).bindparams(value=anomaly_id)
                ).scalar_one()
                == 0
            )
            assert (
                conn.execute(
                    text(
                        "SELECT count(*) FROM rule_detector_state WHERE rule_id = :value"
                    ).bindparams(value=rule_id)
                ).scalar_one()
                == 0
            )
    finally:
        engine.dispose()


@pytest.mark.parametrize(
    "blocker", ["triage", "policy", "suppression", "suppression_hit", "template"]
)
def test_0060_downgrade_refuses_while_a_rule_record_exists(
    clean_db: str, blocker: str
) -> None:
    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(cfg, "0060")
        _seed_blocker(engine, blocker)

        with pytest.raises(RuntimeError, match="cannot downgrade 0060"):
            _downgrade(cfg)

        assert _version(engine) == "0060"
        for table in _NEW_TABLES:
            assert _table_exists(engine, table), table

        _clear_blockers(engine)
        _downgrade(cfg)
        assert _version(engine) == "0059"
    finally:
        engine.dispose()


def test_0060_downgrade_succeeds_when_no_rule_record_exists(clean_db: str) -> None:
    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(cfg, "0060")
        _downgrade(cfg)
        assert _version(engine) == "0059"
        for table in _NEW_TABLES:
            assert not _table_exists(engine, table), table
        command.upgrade(cfg, "0060")
        assert _version(engine) == "0060"
    finally:
        engine.dispose()
