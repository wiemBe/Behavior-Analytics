"""Migration 0020: additive catch-all senders, round trip and no drift."""

from __future__ import annotations

import os

import pytest
from sqlalchemy import create_engine, text

pytestmark = pytest.mark.integration

TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    engine = create_engine(sync_url, future=True)
    with engine.begin() as connection:
        connection.execute(text("DROP SCHEMA public CASCADE"))
        connection.execute(text("CREATE SCHEMA public"))
    engine.dispose()
    return sync_url


def _exists(connection, table: str) -> bool:  # type: ignore[no-untyped-def]
    return bool(
        connection.execute(
            text("SELECT to_regclass(:table)").bindparams(table=f"public.{table}")
        ).scalar()
    )


def _columns(connection, table: str) -> dict[str, tuple[str, str]]:  # type: ignore[no-untyped-def]
    return {
        row.column_name: (row.data_type, row.is_nullable)
        for row in connection.execute(
            text(
                "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
                "WHERE table_name = :t"
            ).bindparams(t=table)
        )
    }


def test_0020_round_trip_constraints_and_no_drift(clean_db: str) -> None:
    from alembic.script import ScriptDirectory
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    assert ScriptDirectory.from_config(config).get_revision("0020").down_revision is not None
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "0020")
        with engine.connect() as connection:
            assert _columns(connection, "catchall_sender") == {
                "id": ("uuid", "NO"),
                "instance_id": ("uuid", "NO"),
                "catchall_log_source_id": ("uuid", "NO"),
                "identifier": ("character varying", "NO"),
                "first_seen_at": ("timestamp with time zone", "NO"),
                "last_seen_at": ("timestamp with time zone", "NO"),
                "events_24h": ("bigint", "YES"),
                "active": ("boolean", "NO"),
                "retired_at": ("timestamp with time zone", "YES"),
                "review_status": ("character varying", "NO"),
                "reviewed_by": ("character varying", "YES"),
                "reviewed_at": ("timestamp with time zone", "YES"),
                "created_at": ("timestamp with time zone", "NO"),
                "updated_at": ("timestamp with time zone", "NO"),
            }
            bucket = _columns(connection, "catchall_bucket")
            assert set(bucket) == {
                "catchall_log_source_id", "bucket_start", "bucket_seconds", "events", "records",
                "distinct_senders", "distinct_senders_lower_bound", "measurement",
                "top_senders", "admitted", "below_admission_threshold", "rejected_over_quota",
                "untracked_senders", "untracked_events", "query_provenance", "collected_at",
            }
            assert bucket["top_senders"] == ("jsonb", "NO")
            assert bucket["query_provenance"] == ("jsonb", "NO")
            unique = connection.execute(
                text(
                    "SELECT array_agg(att.attname ORDER BY ordinality) FROM pg_constraint con "
                    "JOIN unnest(con.conkey) WITH ORDINALITY AS key(attnum, ordinality) ON true "
                    "JOIN pg_attribute att ON att.attrelid = con.conrelid "
                    "AND att.attnum = key.attnum "
                    "WHERE con.conrelid = 'catchall_sender'::regclass AND con.contype = 'u' "
                    "GROUP BY con.oid"
                )
            ).scalar_one()
            assert unique == ["instance_id", "catchall_log_source_id", "identifier"]
            pk = connection.execute(
                text(
                    "SELECT array_agg(att.attname ORDER BY ordinality) FROM pg_constraint con "
                    "JOIN unnest(con.conkey) WITH ORDINALITY AS key(attnum, ordinality) ON true "
                    "JOIN pg_attribute att ON att.attrelid = con.conrelid "
                    "AND att.attnum = key.attnum "
                    "WHERE con.conrelid = 'catchall_bucket'::regclass AND con.contype = 'p' "
                    "GROUP BY con.oid"
                )
            ).scalar_one()
            assert pk == ["catchall_log_source_id", "bucket_start"]
            seeded = connection.execute(
                text(
                    "SELECT cadence_seconds FROM search_cadence WHERE family = 'CATCHALL_SENDERS'"
                )
            ).scalar_one()
            assert seeded == 3600
            hypertable = connection.execute(
                text(
                    "SELECT count(*) FROM timescaledb_information.hypertables "
                    "WHERE hypertable_name = 'catchall_bucket'"
                )
            ).scalar_one()
            assert hypertable == 1

        command.downgrade(config, "0017")
        with engine.connect() as connection:
            assert not _exists(connection, "catchall_sender")
            assert not _exists(connection, "catchall_bucket")
            assert _exists(connection, "ips_source_profile")
            assert not connection.execute(
                text("SELECT 1 FROM search_cadence WHERE family = 'CATCHALL_SENDERS'")
            ).first()

        command.upgrade(config, "0020")
        with engine.connect() as connection:
            assert _exists(connection, "catchall_sender") and _exists(connection, "catchall_bucket")
        # Drift is checked at head, so a later migration cannot hide a model gap.
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()
