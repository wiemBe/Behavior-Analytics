TEST_DB_URL = os.environ.get("TEST_DATABASE_URL")
INSTANCE = "11111111-1111-1111-1111-111111111111"
SOURCE = "22222222-2222-2222-2222-222222222222"


def _sync_url() -> str:
    if not TEST_DB_URL:
        pytest.skip("TEST_DATABASE_URL not set")
    return TEST_DB_URL.replace("+asyncpg", "+psycopg")


def _alembic_config(sync_url: str):  # type: ignore[no-untyped-def]
    from alembic.config import Config

    # Deliberately no alembic.ini: fileConfig() would disable app.* loggers for
    # every integration test that follows this one in the same process.
    config = Config()
    config.set_main_option("script_location", "alembic")
    config.set_main_option("sqlalchemy.url", sync_url)
    return config


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def _seed_scope(connection) -> None:  # type: ignore[no-untyped-def]
    connection.execute(
        text(
            "INSERT INTO qradar_instance (id, name, console_host, api_version, verify_ssl, "
            "provider_kind, mcp_enabled, enabled, status, consecutive_failures) "
            "VALUES (CAST(:instance AS uuid), 'lab', 'qradar.lab.local', '20.0', true, "
            "'REST', false, true, 'HEALTHY', 0)"
        ),
        {"instance": INSTANCE},
    )
    connection.execute(
        text(
            "INSERT INTO log_source (id, instance_id, qradar_id, name, enabled, criticality, "
            "monitoring_enabled, maintenance_mode, business_hours_only, business_hours_start, "
            "business_hours_end, business_days, timezone_name, custom_thresholds, first_seen_at) "
            "VALUES (CAST(:source AS uuid), CAST(:instance AS uuid), 17, 'edge-fw', true, "
            "'MEDIUM', true, false, false, 8, 18, CAST('[1,2,3,4,5]' AS jsonb), 'UTC', "
            "CAST('{}' AS jsonb), now())"
        ),
        {"instance": INSTANCE, "source": SOURCE},
    )


def _watch_insert_sql() -> str:
    return (
        "INSERT INTO property_watch (id, instance_id, name, scope_kind, log_source_id, "
        "scope_type_id, scope_group_id, properties, pinned_values, detectors, severity, "
        "watch_version, enabled) VALUES (gen_random_uuid(), CAST(:instance AS uuid), :name, "
        ":scope_kind, CAST(:log_source_id AS uuid), :scope_type_id, :scope_group_id, "
        "CAST(:properties AS jsonb), CAST('[]' AS jsonb), CAST('[]' AS jsonb), 'MEDIUM', 1, false)"
    )


def _valid_watch_params(name: str) -> dict[str, object]:
    return {
        "instance": INSTANCE,
        "name": name,
        "scope_kind": "LOG_SOURCE",
        "log_source_id": SOURCE,
        "scope_type_id": None,
        "scope_group_id": None,
        "properties": json.dumps([{"kind": "NORMALIZED", "name": "username"}]),
    }


def _rejects(engine, params: Mapping[str, object], constraint: str) -> None:  # type: ignore[no-untyped-def]
    with pytest.raises(IntegrityError, match=constraint), engine.begin() as connection:
        connection.execute(text(_watch_insert_sql()), params)


def test_0026_round_trip_hypertables_seed_and_no_drift(clean_db: str) -> None:
    from alembic.runtime.migration import MigrationContext
    from alembic.script import ScriptDirectory
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    config = _alembic_config(clean_db)
    script = ScriptDirectory.from_config(config)
    heads = script.get_heads()
    assert len(heads) == 1
    assert "0026" in {item.revision for item in script.walk_revisions("base", heads[0])}
    revision = script.get_revision("0026")
    assert revision is not None
    assert revision.down_revision == "0025"

    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(config, "0025")
        with engine.begin() as connection:
            _seed_scope(connection)

        command.upgrade(config, "0026")
        with engine.begin() as connection:
            context = MigrationContext.configure(connection)
            assert context.get_current_revision() == "0026"
            tables = {
                row[0]
                for row in connection.execute(
                    text(
                        "SELECT tablename FROM pg_tables WHERE schemaname = 'public' "
                        "AND (tablename = 'property_watch' OR tablename LIKE 'pw_%')"
                    )
                )
            }
            assert tables == {
                "property_watch",
                "pw_bucket",
                "pw_value",
                "pw_value_metric",
                "pw_value_baseline",
                "pw_detector_state",
                "pw_anomaly",
                "pw_anomaly_transition",
            }
            assert connection.execute(
                text(
                    "SELECT cadence_seconds FROM search_cadence "
                    "WHERE family = 'PROPERTY_WATCH'"
                )
            ).scalar_one() == 3600
            assert connection.execute(
                text("SELECT 1 FROM pg_extension WHERE extname = 'timescaledb'")
            ).scalar_one() == 1
            hypertables = {
                row[0]
                for row in connection.execute(
                    text(
                        "SELECT hypertable_name FROM timescaledb_information.hypertables "
                        "WHERE hypertable_name IN ('pw_bucket', 'pw_value_metric')"
                    )
                )
            }
            assert hypertables == {"pw_bucket", "pw_value_metric"}
            connection.execute(
                text(_watch_insert_sql()), _valid_watch_params("survives-first-upgrade")
            )

        command.downgrade(config, "0025")
        with engine.connect() as connection:
            context = MigrationContext.configure(connection)
            assert context.get_current_revision() == "0025"
            assert connection.execute(
                text("SELECT to_regclass('public.property_watch')")
            ).scalar() is None
            assert connection.execute(
                text("SELECT count(*) FROM search_cadence WHERE family = 'PROPERTY_WATCH'")
            ).scalar_one() == 0
            assert connection.execute(
                text("SELECT name FROM log_source WHERE id = CAST(:source AS uuid)"),
                {"source": SOURCE},
            ).scalar_one() == "edge-fw"

        command.upgrade(config, "head")
        with engine.connect() as connection:
            context = MigrationContext.configure(connection)
            assert context.get_current_revision() == script.get_heads()[0]
            assert connection.execute(
                text("SELECT count(*) FROM search_cadence WHERE family = 'PROPERTY_WATCH'")
            ).scalar_one() == 1
            hypertables = {
                row[0]
                for row in connection.execute(
                    text(
                        "SELECT hypertable_name FROM timescaledb_information.hypertables "
                        "WHERE hypertable_name IN ('pw_bucket', 'pw_value_metric')"
                    )
                )
            }
            assert hypertables == {"pw_bucket", "pw_value_metric"}
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")
    finally:
        engine.dispose()


@pytest.mark.parametrize(
    ("case", "changes", "constraint"),
    [
        (
            "zero-scope-columns",
            {"log_source_id": None},
            "ck_property_watch_scope_matches_kind",
        ),
        (
            "two-scope-columns",
            {"scope_type_id": 368},
            "ck_property_watch_scope_matches_kind",
        ),
        (
            "zero-properties",
            {"properties": "[]"},
            "ck_property_watch_properties_one_or_two",
        ),
        (
            "three-properties",
            {
                "properties": json.dumps(
                    [
                        {"kind": "CUSTOM_PROPERTY", "name": "A"},
                        {"kind": "CUSTOM_PROPERTY", "name": "B"},
                        {"kind": "CUSTOM_PROPERTY", "name": "C"},
                    ]
                )
            },
            "ck_property_watch_properties_one_or_two",
        ),
    ],
    ids=lambda value: value if isinstance(value, str) else None,
)
def test_property_watch_checks_refuse_invalid_shape(
    clean_db: str,
    case: str,
    changes: Mapping[str, object],
    constraint: str,
) -> None:
    from alembic import command

    config = _alembic_config(clean_db)
    command.upgrade(config, "head")
    engine = create_engine(clean_db, future=True)
    try:
        with engine.begin() as connection:
            _seed_scope(connection)
        params = _valid_watch_params(f"reject-{case}")
        params.update(changes)
        _rejects(engine, params, constraint)
    finally:
        engine.dispose()
