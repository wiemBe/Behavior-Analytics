"""Migration 0059: the per-user queue marker table, constraints and drift.

Runs the real revision up, down and up again without ``alembic.ini`` so the process-wide
logging configuration is untouched (AGENTS.md §4). DB-gated.
"""

from __future__ import annotations

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

from tests.integration.schema_reset import reset_public_schema
from tests.integration.test_migrations import _alembic_config, _sync_url, _table_exists

pytestmark = pytest.mark.integration


@pytest.fixture
def clean_db() -> str:
    sync_url = _sync_url()
    reset_public_schema(sync_url)
    return sync_url


def test_0059_round_trip_constraints_and_drift(clean_db: str) -> None:
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = _alembic_config(clean_db)
    engine = create_engine(clean_db, future=True)
    try:
        command.upgrade(cfg, "0058")
        assert not _table_exists(engine, "user_queue_marker")

        command.upgrade(cfg, "0059")
        assert _table_exists(engine, "user_queue_marker")

        insert = "INSERT INTO user_queue_marker (owner_subject, marked_at) VALUES ('{s}', {t})"
        with engine.begin() as conn:
            conn.execute(text(insert.format(s="a", t="'2026-11-07 06:00+00'")))
            updated_at = conn.execute(
                text("SELECT updated_at FROM user_queue_marker WHERE owner_subject = 'a'")
            ).scalar_one()
            assert updated_at is not None
        # One row per subject, and the marker itself is never null.
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(insert.format(s="a", t="'2026-11-07 07:00+00'")))
        with pytest.raises(IntegrityError), engine.begin() as conn:
            conn.execute(text(insert.format(s="b", t="NULL")))

        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected between models and migrations:\n{exc}")

        command.downgrade(cfg, "0058")
        assert not _table_exists(engine, "user_queue_marker")
        command.upgrade(cfg, "head")
        assert _table_exists(engine, "user_queue_marker")
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"schema drift detected after the round trip:\n{exc}")
    finally:
        engine.dispose()
